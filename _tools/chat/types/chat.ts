// ТИПЫ ИНСТРУМЕНТА «ЧАТ» — договор между лентой и тем, кто её наполняет (шаг 80-4).
//
// 🔒 ИНСТРУМЕНТ НЕ ЗНАЕТ, ОТКУДА ПРИЕХАЛИ СООБЩЕНИЯ. Журнал Telegram-бота, будущий
// мессенджер на `useChat`, образец в каталоге блоков — все три переводят своё в
// эти типы. Иначе лента начала бы разбираться в чужих складах, и у каждого
// потребителя выросла бы своя ветка внутри общего компонента.

/** Кто говорит. Совпадает с ролями библиотеки: человек слева, ответ справа. */
export type ChatRole = "user" | "assistant";

/**
 * Вложение сообщения.
 *
 * 🔒 ЧЕТЫРЕ ПЕРВЫХ РОДА — НАТИВНЫЕ ДЛЯ БИБЛИОТЕКИ, ДВА ПОСЛЕДНИХ НАШИ (разведка
 * 80-1). Аудио, изображение, видео и документ `Attachments` узнаёт сам по типу
 * содержимого; места и календарного события в библиотеке нет вовсе, и они
 * рисуются нами — в том же ряду, чтобы лента не разъезжалась на два узора.
 */
export type ChatAttachment =
  | {
      kind: "audio" | "image" | "video" | "document";
      /** Адрес файла. Пустой строки быть не должно: вложение без адреса — это подпись, а не файл. */
      url: string;
      mediaType?: string;
      name?: string;
    }
  | { kind: "place"; lat: number; lon: number; label?: string | null }
  | { kind: "event"; at: string; title: string; note?: string | null };

/** Одно сообщение ленты. */
export type ChatMessage = {
  id: string;
  from: ChatRole;
  text?: string | null;
  /** ISO-время. Показывается, когда дано. */
  at?: string | null;
  /** Кто написал: `@имя`, имя человека или пусто. */
  who?: string | null;
  /**
   * Чем сообщение создано.
   *
   * 🔒 НЕОБЯЗАТЕЛЬНОЕ И СЕГОДНЯ ПУСТОЕ — решение владельца 80-2. Пока канал один,
   * пометка не значит ничего; в день, когда рядом с Telegram-ботом появится
   * мессенджер на сайте, она уже будет и на месте, и нарисованной.
   */
  source?: string | null;
  /** Пересланное сообщение: от кого. */
  forwardedFrom?: string | null;
  attachments?: ChatAttachment[];
};

/** Что уезжает наружу, когда человек нажал «отправить». */
export type ChatSendPayload = {
  text: string;
  files: { url: string; mediaType: string; filename?: string }[];
};

/**
 * Слова инструмента.
 *
 * 🔒 ОСТРОВКУ ОТДАЮТСЯ ТОЛЬКО ЕГО СЛОВА, ПЕРЕЧИСЛЕННЫЕ ПОИМЁННО (закон шага 25):
 * тип не сужает рантайм, и по проводу уезжает всё переданное, даже неотрисованное.
 */
export type ChatUi = {
  /** Пустая лента: заголовок и пояснение. */
  emptyTitle: string;
  emptyNote: string;
  /** Поле ввода. */
  placeholder: string;
  send: string;
  attach: string;
  /** Подписи двух наших вложений. */
  place: string;
  event: string;
  /** Приставка к пересланному сообщению. */
  forwarded: string;
};
