// ЧЕРНОВИК ТИПИЗИРОВАННОЙ ЗАПИСИ — договор инструмента (81-5).
//
// 🔒 ИНСТРУМЕНТ НЕ ЗНАЕТ СЛОВА «ПРИЗНАК», И ЭТО СДЕЛАНО НАМЕРЕННО. Он превращает
// свободное описание человека в запись по ПЕРЕДАННОЙ схеме полей. Первый его
// потребитель — реестр признаков; второй возьмёт его для чего угодно, где
// человек описывает словами то, что коду нужно полями.
//
// 🔒 ОТВЕТ ПРЕДЛАГАЕТСЯ, А НЕ ПРИМЕНЯЕТСЯ — закон `socials-ai`, взятый дословно.
// Инструмент ничего не пишет: он возвращает черновик, а сохраняет человек,
// посмотрев на типы. Модель ошибается тихо, и единственная защита от этого —
// глаза владельца между предложением и записью.

/** Поле, которое инструмент обязан заполнить. Схему задаёт потребитель. */
export type DraftField = {
  /** Машинное имя поля в ответе. */
  name: string
  /** Что это, словами — едет в модель как объяснение. */
  about: string
  /**
   * Закрытый список допустимых значений. Пусто — свободный текст.
   *
   * 🔒 ЗАКРЫТЫЙ СПИСОК ПРОВЕРЯЕТСЯ НАМИ, А НЕ ОБЕЩАЕТСЯ МОДЕЛЬЮ. Она охотно
   * вернёт значение, которого в списке нет, и выглядеть это будет правдоподобно.
   */
  oneOf?: readonly string[]
  /** Поле обязательно: без него черновик бессмыслен. */
  required?: boolean
}

/** Что вернулось. Успех и отказ различимы по форме, а не по пустоте. */
export type DraftResult =
  | { ok: true; draft: Record<string, string>; notes: string }
  | { ok: false; reason: DraftFailure }

/**
 * Почему не вышло.
 *
 * 🔒 «НЕ ПОНЯЛ» — ЗАКОННЫЙ ИСХОД, А НЕ ПОЛОМКА. Человек мог сказать бессмыслицу
 * или слишком коротко; притвориться, что мы разобрали, и вернуть выдуманную
 * запись — хуже отказа, потому что она сохранится и будет выглядеть настоящей.
 */
export type DraftFailure =
  /** Ключа модели нет: инструмент молчит, форма продолжает работать руками. */
  | "no-key"
  /** Описание слишком короткое, чтобы из него что-то вышло. */
  | "too-short"
  /** Модель не ответила или ответила не JSON. */
  | "model-silent"
  /** Модель честно сказала, что не поняла, о чём речь. */
  | "not-understood"
