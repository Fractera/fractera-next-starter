/**
 * Чем закончилась проверка адреса.
 *
 * 🔒 ИСХОДОВ ТРИ, А НЕ ДВА, И ЭТО СУТЬ, А НЕ ДОТОШНОСТЬ. Instagram и LinkedIn
 * закрываются от ботов НЕЗАВИСИМО от того, существует профиль или нет. Свести
 * `closed` к «нет» значит уверенно предложить владельцу не тот профиль — соврать
 * тихо, а тихая ложь здесь дороже отказа.
 */
export type SocialOutcome = "exists" | "absent" | "closed"

export type SocialCandidate = {
  /** Псевдоним или номер — то, что подставляется в шаблон. */
  value: string
  /** Собранный адрес: его человек и увидит. */
  url: string
  outcome: SocialOutcome
  /** Код ответа сети; `null` — не ответила вовсе. */
  code: number | null
}

export type SocialProposal = {
  ok: true
  /** Каноническое имя сети — так, как её пишет владелец бренда. */
  name: string
  /** Ключ значка из нашего каталога; пусто — знака нет. */
  iconKey: string
  /** Правило сборки адреса с подстановкой `{value}`. */
  urlTemplate: string
  /** Что человеку надо ввести — на его языке. */
  valueHint: string
  candidates: SocialCandidate[]
}

/**
 * Отказ.
 *
 * 🔒 У КАЖДОГО ОТКАЗА СВОЁ ИМЯ, И У КАЖДОГО ЕСТЬ ВЫХОД РУКАМИ. Без ключа модели
 * конструктор соцсетей не должен переставать работать: сети заводят и без ИИ.
 */
export type SocialRefusal = {
  ok: false
  reason: "no-key" | "unknown-network" | "model"
  detail?: string
}

export type SocialResolveResult = SocialProposal | SocialRefusal
