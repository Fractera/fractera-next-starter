"use client";

import { useState } from "react";
import { ChevronDown } from "lucide-react";
import type { ReactNode } from "react";

// СВЁРНУТАЯ СПРАВКА РАЗДЕЛА — ОБЩАЯ НА ВЕСЬ СЛОЙ (2026-08-31).
//
// 🔒 ПОДНЯТА, А НЕ СКОПИРОВАНА (76-2). Раньше файл назывался `blocks-intro` и
// принадлежал одному разделу. Потребителей стало двое — «Блоки» и
// «Инструменты», — и вторая редакция того же островка разошлась бы с первой на
// первой же правке текста, причём разошлась бы в том разделе, который реже
// открывают. Единственное, что стало настраиваемым, — имя в `data-section-intro`:
// по нему замер отличает справку одного раздела от справки другого.
//
// Заказ владельца дословно: «на странице про блоки мы добавили информацию, но она
// занимает очень много пространства — сделай по умолчанию, чтобы было видно три
// строчки и кнопка „узнать больше“; нажатие раскрывает весь контейнер, но по
// умолчанию контейнер остаётся скрытым; любое переключение вкладки возвращает
// состояние контейнера скрытый, не надо в памяти держать открытый контейнер».
//
// 🪦 ЭТО ОТМЕНЯЕТ ЕГО ЖЕ РЕШЕНИЕ ОТ 2026-08-30, И ОТМЕНЁННОЕ НАЗВАНО ЗДЕСЬ, А НЕ
// СТЁРТО. Тогда он потребовал, чтобы ЧЕТВЁРТЫЙ абзац (про параллельную
// маршрутизацию) был виден, а не свёрнут: «свёрнутый ответ на такой вопрос равен
// отсутствующему». Теперь свёрнута вся справка целиком. Причина не в том, что
// прежний довод стал неверен, а в том, что справка выросла и вытеснила собой
// каталог — то, ради чего страницу открывают. Довод остаётся в силе для одного
// абзаца и перестаёт работать, когда абзацев четыре.
//
// 🔒 СОСТОЯНИЕ НЕ ПЕРЕЖИВАЕТ ПЕРЕКЛЮЧЕНИЕ ВКЛАДКИ, И ЭТО СДЕЛАНО КОНСТРУКЦИЕЙ, А
// НЕ ПРИСМОТРОМ. Владелец сказал прямо: «не надо в памяти держать открытый
// контейнер». Компонент ничего не помнит между переходами: раскрытие живёт в
// обычном состоянии React, а сверху ему дан `key`, куда входят и раздел, и
// выбранный тип блока. Смена любого из двух — новый ключ, новый экземпляр,
// свёрнутый вид. Хранилище браузера здесь было бы прямо противоположно просьбе.
//
// 🔒 СВЁРНУТЫЙ ВИД ПОКАЗЫВАЕТ ПЕРВЫЙ АБЗАЦ, ОБРЕЗАННЫЙ ТРЕМЯ СТРОКАМИ, А НЕ
// «ПЕРВЫЕ ТРИ СТРОКИ ВСЕХ ЧЕТЫРЁХ». Обрезать высотой контейнер из четырёх
// абзацев можно только числом в пикселях, а оно врёт при другом кегле, другом
// языке и другой ширине окна. `line-clamp` считает строки сам и знает про
// перенос — но работает по одному текстовому блоку, и потому свёрнутым показан
// ровно один: тот, который отвечает на вопрос «что такое блок».

export function SectionIntro({
  name,
  summary,
  rest,
  moreLabel,
  lessLabel,
}: {
  /** Чей это раздел — уезжает в `data-section-intro` и больше ни на что не влияет. */
  name: string;
  /** Первый абзац: он и виден в свёрнутом виде, обрезанный тремя строками. */
  summary: ReactNode;
  /** Всё остальное — появляется только по нажатию. */
  rest: ReactNode;
  moreLabel: string;
  lessLabel: string;
}) {
  const [open, setOpen] = useState(false);

  return (
    <section
      data-section-intro={name}
      data-open={open ? "true" : "false"}
      className="rounded-lg border border-border bg-card p-4 sm:p-5"
    >
      <div className="flex flex-col gap-3">
        {/* Свёрнутый — три строки; раскрытый — целиком. */}
        <div className={open ? undefined : "line-clamp-3"}>{summary}</div>
        {open && rest}
      </div>

      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        data-section-intro-toggle={name}
        className="mt-3 inline-flex items-center gap-1.5 text-[length:var(--fs-small)] text-muted-foreground transition-colors hover:text-foreground"
      >
        <ChevronDown
          size={13}
          aria-hidden
          className={`shrink-0 transition-transform ${open ? "rotate-180" : ""}`}
        />
        {open ? lessLabel : moreLabel}
      </button>
    </section>
  );
}
