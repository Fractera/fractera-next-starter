import type { ReactNode } from "react"
import { ChevronRight } from "lucide-react"
import { H4 } from "@/components/ui/typography"

// СКЛАДНАЯ КАРТОЧКА РАЗДЕЛА «НАСТРОЙКИ» (111, 2026-09-04).
//
// Заказ владельца дословно: «у нас вкладка Telegram боты имеет возможность
// схлопываться. Это стандартные свойства аккордеона. Сделай так чтобы все
// остальные вкладки… также закрывались как аккордеон».
//
// 🔒 ОДНА РЕАЛИЗАЦИЯ НА ЧЕТЫРЕ КАРТОЧКИ, А НЕ ЧЕТЫРЕ КОПИИ РАЗМЕТКИ. Ключ
// OpenAI, расписание, реестр признаков и реестр инструментов несли одинаковую
// шапку `border-b px-3 py-2`, набранную в каждом файле заново. Четыре копии —
// не четыре реализации, а четыре возможности разойтись: правку вида получит та,
// которую вспомнили, а остальные отстанут молча.
//
// 🔒 РАСКРЫТИЕ ДЕЛАЕТ `<details>` БРАУЗЕРА, БЕЗ ЕДИНОЙ СТРОКИ JS — тот же приём,
// что у карточки бота (99-4) и у строки признака (81-9). Закон слоя велит сперва
// спросить, нужен ли островок: здесь не нужен, состояние «раскрыто» держит сам
// браузер, и это работает даже когда скрипты не доехали.
//
// 🔒 ВЗАИМНОГО ИСКЛЮЧЕНИЯ ЗДЕСЬ НЕТ, И ЭТО РАЗНИЦА С КАРТОЧКАМИ БОТОВ. Общий
// атрибут `name` у ботов означает «виден ровно один» — прямое требование
// владельца, потому что боты однородны и человеку нужен один за раз. Эти четыре
// карточки про РАЗНОЕ: закрывать расписание при открытии реестра значило бы
// мешать работе, а не помогать ей.
//
// 🔒 СВЁРНУТАЯ КАРТОЧКА ГОВОРИТ СВОЁ СОСТОЯНИЕ ЗАГОЛОВКОМ — для того и есть
// `status`. У ключа OpenAI это «задан · частично · не задан», у реестра
// признаков — счётчик. Свернуть то, что молчит, значит спрятать правду: карточка
// бота ровно поэтому несёт «привязан/не привязан» в самой строке заголовка.
export function SettingsCard({
  icon,
  title,
  status,
  open = false,
  bodyClassName = "p-3",
  mark,
  children,
}: {
  /** Значок слева от названия — тот же, что стоял в прежней шапке карточки. */
  icon: ReactNode
  title: string
  /** Правая часть строки заголовка: плашка состояния, счётчик, кнопка. */
  status?: ReactNode
  /** Раскрыта ли при первой загрузке. По умолчанию — нет: страница компактная. */
  open?: boolean
  bodyClassName?: string
  /**
   * Признаки разметки карточки (`data-openai-key`, `data-facts-registry`).
   *
   * 🔒 ОНИ ПЕРЕЕЗЖАЮТ НА `<details>`, А НЕ ИСЧЕЗАЮТ: по ним считает доказательство
   * шага и любая будущая проверка. Признак, потерянный при переносе разметки,
   * гасит счётчик в ноль и выглядит как пропавшая способность.
   */
  mark?: Record<string, string>
  children: ReactNode
}) {
  return (
    <details className="rounded-lg border border-border" open={open} {...mark}>
      <summary className="flex cursor-pointer flex-wrap items-center gap-2 px-3 py-2 [&::-webkit-details-marker]:hidden [details[open]_&]:border-b [details[open]_&]:border-border">
        <ChevronRight className="size-4 shrink-0 text-muted-foreground transition-transform [details[open]_&]:rotate-90" />
        <span className="flex flex-1 items-center gap-2">
          {icon}
          <H4 variant="ui">{title}</H4>
        </span>
        {status}
      </summary>

      <div className={bodyClassName}>{children}</div>
    </details>
  )
}
