//
// 🔒 ПЕРЕНОС ИЗ СЛОВАРЯ ПАНЕЛИ ДОСЛОВНО. Источник — `lib/i18n/admin-translations.json`,
// ветка `projectTypes`. Владелец продиктовал эти вопросы по каждой теме двумя
// независимыми наборами (2026-08-16); переписать их «покрасивее» при переносе
// значило бы выбросить работу, которую он сделал руками.
//
// 🔒 ЛОВУШКА, НАЙДЕННАЯ РАЗВЕДКОЙ 34: В СЛОТЕ `config/project-types.ts` УСЕЧЁН.
// Там только идентификаторы — 22 машинных имени и порядок. Определения, примеры,
// признаки и **вопросы под каждое направление** жили ТОЛЬКО в панели. Без них
// выбор типа не даёт вводных вопросов, а именно они отвечают на первые семь
// вопросов Quiz: перенести кейсы и не перенести это значило бы получить пустой
// опрос у всех двадцати двух направлений.
//
// 🔒 ФАЙЛ СЕРВЕРНЫЙ (`server-only`), И ЭТО НЕ ОСТОРОЖНОСТЬ, А АРИФМЕТИКА.
// 306 КБ на два языка; отдать его браузеру значит грузить треть мегабайта на
// каждой загрузке страницы ради одного выбранного направления. Островку едут
// строки ОДНОГО типа, выбранные на сервере.
//
// 🔒 ЗДЕСЬ `en` И `ru`. В панели их тоже два — остальные восемьдесят она не имеет
// и для этой ветки: вопросы диктовал владелец, а не машинный перевод.

export type ProjectTypeWords = {
  title: string
  /** Одна строка под именем: чем это направление отличается от соседнего. */
  tagline: string
  /** Что это такое, развёрнуто. */
  definition: string
  /** Примеры, по которым человек узнаёт своё. Список — их несколько. */
  examples: string[]
  /** Признаки: как понять, что это про тебя. Список. */
  signals: string[]
  /**
   * Вводные вопросы ИМЕННО под это направление.
   *
   * 🔒 НИ ОДИН ВОПРОС НЕ ПЕРЕИСПОЛЬЗУЕТСЯ МЕЖДУ ТИПАМИ, и это следствие
   * устройства, а не стиль: «сколько шагов в оформлении заказа» бессмысленно для
   * мозга компании, а «что считаем одним конкурентом» — для посадочной страницы.
   * Общий вопрос дал бы общий ответ, общий ответ — общий кейс, и выбор структуры
   * перестал бы что-либо решать. Ровно эту беду он и лечит.
   *
   * 🔒 ПУСТОЙ СПИСОК ЕСТЬ РОВНО У `custom`, И ЭТО ЕГО СМЫСЛ, А НЕ УПУЩЕНИЕ.
   */
  questions: string[]
}

const DICT = words as Record<string, Record<string, ProjectTypeWords>>

function langOf(lang: string): Record<string, ProjectTypeWords> {
  return DICT[lang] ?? DICT[lang.slice(0, 2)] ?? DICT.en
}

/** Слова одного направления на языке страницы. */
export function projectTypeWords(lang: string, id: ProjectTypeId): ProjectTypeWords | null {
  return langOf(lang)[id] ?? null
}

/**
 * Короткие карточки всех направлений — для экрана выбора.
 *
 * 🔒 БЕЗ ВОПРОСОВ И БЕЗ ОПРЕДЕЛЕНИЙ. На экране выбора их не показывают, а
 * отдать островку весь словарь значило бы вернуть те самые 306 КБ, ради которых
 * файл и объявлен серверным.
 */
export function projectTypeCards(lang: string): { id: ProjectTypeId; title: string; tagline: string }[] {
  const w = langOf(lang)
  return PROJECT_TYPES.map(id => ({
    id,
    title: w[id]?.title ?? id,
    tagline: w[id]?.tagline ?? "",
  }))
}

/** Вводные вопросы направления. Пусто — законное состояние (`custom`). */
export function questionsFor(lang: string, id: ProjectTypeId): string[] {
  return langOf(lang)[id]?.questions ?? []
}
