// которого не существует.

// 🔒 «ВИДИМОСТЬ» СТОИТ ВТОРОЙ ПО ПРЯМОМУ СЛОВУ ВЛАДЕЛЬЦА (78-4, 2026-08-31):
// «это будет второй вкладкой сверху в левом меню». Место содержательно: сначала
// решают, ЕСТЬ ли вход на сайте вообще, и только потом — какими провайдерами он
// открывается. Провайдер, настроенный при выключенном входе, не появится нигде,
// и человек, начавший с третьего раздела, искал бы ошибку в ключах.
export const AUTH_SECTIONS = ["about", "visibility", "google", "resend"] as const
export type AuthSection = (typeof AUTH_SECTIONS)[number]

export function isAuthSection(v: unknown): v is AuthSection {
  return typeof v === "string" && (AUTH_SECTIONS as readonly string[]).includes(v)
}

/**
 * Какой раздел открыт.
 *
 * 🔒 НЕИЗВЕСТНОЕ ЗНАЧЕНИЕ ПАДАЕТ НА ПЕРВЫЙ РАЗДЕЛ, А НЕ НА ПУСТОЙ ЭКРАН. Адрес
 * приходит из строки браузера, то есть от кого угодно; «нет такого раздела»
 * человек читает как поломку проекта, а не как свою опечатку.
 */
export function resolveAuthSection(raw: string | undefined): AuthSection {
  return isAuthSection(raw) ? raw : "about"
}

/** Адрес раздела внутри входа. */
export function hrefOfAuthSection(lang: string, section: AuthSection): string {
  return `/${lang}/architect/auth?section=${section}`
}
