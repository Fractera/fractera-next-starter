export const DESIGN_SECTIONS = ["fonts", "type", "shape", "colors", "blocks"] as const
export type DesignSection = (typeof DESIGN_SECTIONS)[number]

export function isDesignSection(v: unknown): v is DesignSection {
  return typeof v === "string" && (DESIGN_SECTIONS as readonly string[]).includes(v)
}

/**
 * Какой раздел открыт.
 *
 * 🔒 НЕИЗВЕСТНОЕ ЗНАЧЕНИЕ ПАДАЕТ НА ПЕРВЫЙ РАЗДЕЛ, А НЕ НА ПУСТОЙ ЭКРАН. Адрес
 * приходит из строки браузера, то есть от кого угодно; «нет такого раздела»
 * человек читает как поломку проекта, а не как свою опечатку.
 */
export function resolveDesignSection(raw: string | undefined): DesignSection {
  return isDesignSection(raw) ? raw : "fonts"
}

/** Адрес раздела внутри группы. */
export function hrefOfDesignSection(lang: string, section: DesignSection): string {
  return `/${lang}/architect/design?section=${section}`
}
