import { visit } from "unist-util-visit"
import type { Plugin } from "unified"
import type { Root, Text, Parent } from "mdast"
import { passportAnchor } from "./passport-outline"

// ЧТО ИЗМЕНИЛОСЬ В ПАСПОРТЕ ЗА ЭТУ СЕССИЮ — ПОДСВЕЧЕНО ФОНОМ (шаг 98, 2026-09-03).
//
// 🔒 ЗАКАЗ ВЛАДЕЛЬЦА ДОСЛОВНО: «то что приходит в качестве обновлений в каждой
// сессии подсвечивая внутри документа паспорт путём создания Background для
// текста, чтобы я мог на каждом шаге видеть что ты подсвечиваешь в работе что ты
// добавляешь; соответственно каждый следующий шаг начинается с того что ты
// удаляешь все что было раньше выделено и создаешь новое выделение очередного
// шага».
//
// 🛑 СЫРОЙ HTML В ЭТОМ ДОКУМЕНТЕ НЕ РАБОТАЕТ, И ЭТО ИЗМЕРЕНО, А НЕ
// ПРЕДПОЛОЖЕНО. Тело паспорта рисует `Streamdown`, который разметку HTML не
// пропускает: `<mark>` или `<span style>`, вписанные прямо в текст, доехали бы
// до страницы буквами. Тем же и объясняется, почему прокрутка по меню не
// работала — `<a id="…">` из `passportWithAnchors()` до дерева страницы не
// доезжал никогда.
//
// 🔒 ПОЭТОМУ ПОДСВЕТКА И ЯКОРЬ ДЕЛАЮТСЯ ОДНИМ ПРИЁМОМ: узел размечается в
// дереве Markdown, а не строкой в тексте. `data.hName` — то место договора,
// которым mdast говорит, каким элементом стать; никакого HTML в исходнике при
// этом нет вовсе.

/**
 * `==текст==` становится `<mark>`.
 *
 * 🔒 ФОРМА ВЗЯТА У РАСШИРЕНИЯ GFM, А НЕ ПРИДУМАНА. `==…==` — общепринятая
 * запись подсветки: её понимают редакторы, и в чужом просмотрщике документ
 * останется читаемым. Свой значок пришлось бы объяснять каждому, кто откроет
 * файл без нашей страницы.
 *
 * 🛑 ОДНА СТРОКА, А НЕ АБЗАЦ ЦЕЛИКОМ. Подсветка живёт внутри текстового узла:
 * обернуть ею заголовок или ячейку таблицы можно, а перечеркнуть половину
 * документа — нет. Это ограничение намеренное: подсветка, съевшая экран,
 * перестаёт отвечать на вопрос «что здесь новое».
 */
export const remarkPassportMarks: Plugin<[], Root> = () => tree => {
  visit(tree, "text", (node: Text, index, parent: Parent | undefined) => {
    if (!parent || index === undefined || !node.value.includes("==")) return

    const parts = node.value.split(/==([^=]+)==/g)
    if (parts.length === 1) return

    const next: (Text | { type: "emphasis"; data: object; children: Text[] })[] = []
    parts.forEach((piece, i) => {
      if (!piece) return
      if (i % 2 === 1) {
        // Нечётные куски — то, что стояло между парами `==`.
        next.push({
          children: [{ type: "text", value: piece }],
          // 🔒 ТИП БЕРЁМ СУЩЕСТВУЮЩИЙ, А ИМЯ ЭЛЕМЕНТА ЗАДАЁМ ЧЕРЕЗ `hName`.
          // Свой тип узла пришлось бы учить обрабатывать весь конвейер; здесь
          // же обычный `emphasis`, которому сказано стать `<mark>`.
          data: { hName: "mark" },
          type: "emphasis",
        })
      } else {
        next.push({ type: "text", value: piece })
      }
    })

    parent.children.splice(index, 1, ...(next as never[]))
    return index + next.length
  })
}

/**
 * Заголовок первого уровня получает `id` — тот же, что печатает меню раздела.
 *
 * ✗ ОПЛАЧЕНО НАБЛЮДЕНИЕМ ВЛАДЕЛЬЦА 2026-09-03: «страница паспорта имеет вверху
 * навигационное меню, но не имеет возможности прокрутки к данному разделу».
 * Измерено на живой странице: ссылок `href="#p-…"` — есть, целей `id="p-…"` —
 * ноль. Якорь вставлялся в текст сырым HTML и выбрасывался разметчиком.
 *
 * 🔒 ЯКОРЬ СЧИТАЕТ ТА ЖЕ ФУНКЦИЯ, ЧТО СТРОИТ МЕНЮ. Две сборки якоря дают ссылку
 * в никуда, и заметно это не сразу — страница просто не прокручивается.
 */
export const remarkPassportAnchors: Plugin<[], Root> = () => tree => {
  visit(tree, "heading", node => {
    if (node.depth !== 2) return
    const title = node.children
      .map(c => ("value" in c ? c.value : ""))
      .join("")
      .trim()
    if (!title) return
    node.data = { ...node.data, hProperties: { id: passportAnchor(title) } }
  })
}
