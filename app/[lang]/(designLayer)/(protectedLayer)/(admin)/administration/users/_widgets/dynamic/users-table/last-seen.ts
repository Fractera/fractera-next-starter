// «Когда человек последний раз заходил» — в словах, а не голой датой.
//
// 🔒 ПОЧЕМУ ЭТО ЛЕЖИТ ВНУТРИ ВИДЖЕТА, А НЕ В `lib/`. Правило границы: наружу
// выходит то, что отвечает на вопрос «как проект вообще делает X», внутри
// остаётся всё, что отвечает «как выглядит и ведёт себя ЭТА таблица». Проверка
// на границе — вынести наружу и спросить: заставит ли это два виджета быть
// одинаковыми? Заставит: с общим форматтером ни одна таблица проекта уже не
// сможет говорить о времени иначе. Соседняя колонка «Заведена» форматируется
// здесь же, в `row.client.tsx`, — второй дом для той же мысли разошёлся бы с
// первым в первую же правку.
//
// 🔒 СЛОВ ЗДЕСЬ НЕТ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ ФАЙЛА. «3 дня назад», «вчера»,
// «в прошлом месяце» выдаёт `Intl.RelativeTimeFormat` по языку страницы — со
// всеми числительными, которых в русском три формы, а в польском четыре.
// Написать это словарём значило бы завести десять языков × семь единиц времени
// × формы числа и сопровождать их руками; браузер знает это лучше и уже умеет.
//
// 🔒 ТРИ ИСХОДА, А НЕ ДВА. `null` («ни разу не входил») и отсутствие поля
// («служба не присылает колонку») — РАЗНЫЕ события, и именно в этом месте их
// нельзя смешивать: владелец просит колонку, чтобы отличить того, кто завёл
// запись и пропал, от того, кто пользуется. Показав молчание службы как «ни
// разу», мы ответили бы на его вопрос выдумкой. Поэтому функция возвращает
// РОД ответа, а слова к двум пустым родам подставляет вызывающий из словаря.

/** Что удалось сказать о последнем входе. */
export type LastSeen =
  /** Дата есть: `text` — «3 дня назад», `exact` — точное значение для подсказки. */
  | { kind: "at"; text: string; exact: string; days: number }
  /** Служба ответила `null`: запись заведена, вход не состоялся ни разу. */
  | { kind: "never" }
  /** Поля в ответе нет вовсе — сказать нечего, и врать об этом нельзя. */
  | { kind: "unknown" }

/** Единицы сверху вниз: первая, в которую разница укладывается целым числом. */
const UNITS: Array<[Intl.RelativeTimeFormatUnit, number]> = [
  ["year", 365 * 24 * 3600],
  ["month", 30 * 24 * 3600],
  ["week", 7 * 24 * 3600],
  ["day", 24 * 3600],
  ["hour", 3600],
  ["minute", 60],
  ["second", 1],
]

/**
 * Разбирает значение колонки `users.last_login_at`.
 *
 * @param raw что прислала служба: строка даты, `null` (не входил), `undefined` (поля нет)
 * @param lang язык страницы — им же говорит `Intl`
 */
export function lastSeen(raw: string | null | undefined, lang: string): LastSeen {
  if (raw === undefined) return { kind: "unknown" }
  if (raw === null || raw === "") return { kind: "never" }

  const at = new Date(raw)
  // Непонятная строка — это тоже «сказать нечего»: показать `Invalid Date`
  // человеку хуже, чем честно промолчать.
  if (Number.isNaN(at.getTime())) return { kind: "unknown" }

  const seconds = Math.round((at.getTime() - Date.now()) / 1000)
  const past = Math.abs(seconds)

  // `numeric: "auto"` — ради «вчера» и «сейчас» вместо «1 день назад» и
  // «0 секунд назад»: просьба владельца была именно про человеческий вид.
  const rtf = new Intl.RelativeTimeFormat(lang, { numeric: "auto" })
  const [unit, size] = UNITS.find(([, s]) => past >= s) ?? UNITS[UNITS.length - 1]
  // 🔒 ОТБРАСЫВАЕМ ОСТАТОК, А НЕ ОКРУГЛЯЕМ. Округление врёт в бо́льшую сторону:
  // полтора года молчания превращались в «2 года назад» — запись выглядела
  // мёртвее, чем есть, а решения по этой колонке принимает человек. Прошедшее
  // время считают вниз: «год назад» держится, пока не наступит второй.
  const text = rtf.format(Math.trunc(seconds / size), unit)

  return {
    kind: "at",
    text,
    // Точное значение не выбрасывается, а уходит подсказкой: «понятно» не
    // должно означать «непроверяемо».
    exact: at.toLocaleString(lang),
    // Сколько дней молчит запись — этим строка решает, выделять её или нет.
    days: Math.floor(past / (24 * 3600)),
  }
}

/**
 * 🔒 ГРАНИЦА «ПРОПАЛ» — 30 ДНЕЙ, И ОНА ЗДЕСЬ ОДНА.
 *
 * Владелец просил видеть, «кто пользуется, а кто завёл аккаунт и пропал».
 * Слова «месяц назад» это уже говорят, но глаз в списке из ста строк читает не
 * слова, а рисунок, поэтому уснувшая запись гасится цветом. Число выбрано мной
 * и владельцем не подтверждено — менять его здесь, в одном месте.
 */
export const DORMANT_AFTER_DAYS = 30
