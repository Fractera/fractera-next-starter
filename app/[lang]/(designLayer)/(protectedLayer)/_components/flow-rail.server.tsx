import { FLOW_COLOR, type ProtectedGroup } from "@/lib/flows"

// ПОЛОСА ПОТОКА — вертикальная лента у правого края с названием слоя прав.
//
// 🔒 ЗАЧЕМ. Четыре слоя показывают ОДНУ и ту же сущность, отличаясь тем, что в
// ней можно делать. Человек, переключившийся между вкладками, через минуту не
// помнит, в каком качестве он сейчас смотрит на товары, — и удивляется, что
// кнопки другие. Полоса отвечает на этот вопрос, не отнимая ни одного нажатия:
// она просто есть, всё время, одного цвета на весь поток.
//
// 🔒 ПОЧЕМУ ЭТО НЕ ЛОМАЕТ СТАТИКУ. Поток известен из АДРЕСА, а не из сессии:
// маршрут лежит в своей группе прав, значит слой определён на сборке. Полоса —
// серверный компонент без единого запроса: ни `auth()`, ни `cookies()`, ни
// `/api/me`. Она уезжает в предрендер вместе с заголовком страницы, и страница
// остаётся статической ровно настолько, насколько была.
//
// 🔒 ПОЧЕМУ СПРАВА И ПОЧЕМУ `fixed`. Слева у продукта живут меню и крошки —
// место занято. `fixed` держит ленту в поле зрения при прокрутке: смысл её в
// том, чтобы отвечать на вопрос в ЛЮБОЙ момент, а не только наверху страницы.
// На узком экране лента прячется: 24 пикселя ширины там дороже, чем польза, а
// цветная точка в ящике аккаунта отвечает на тот же вопрос.
export function FlowRail({ group, label }: { group: ProtectedGroup; label: string }) {
  const c = FLOW_COLOR[group]

  return (
    <div
      aria-hidden
      className={`fixed right-0 top-14 bottom-0 z-30 hidden w-6 select-none md:block ${c.bg}`}
    >
      {/* Текст повёрнут на 90°: вертикальная надпись читается сверху вниз, и
          именно так её ждёт глаз на боковой ленте. */}
      <div className="flex h-full items-center justify-center">
        <span
          className="whitespace-nowrap text-[10px] font-medium uppercase tracking-[0.2em] text-white"
          style={{ writingMode: "vertical-rl" }}
        >
          {label}
        </span>
      </div>
    </div>
  )
}
