// Свободный слой — страницы с кастомным дизайном (шаг 538).
//
// 🔒 ЧТО ЭТО. Слой без оформления платформы: ни меню, ни подвала, ни выдвижных
// панелей, ни баннера согласия, ни тостов, ни обвязки приложения. Страница получает
// голый `<body>` и рисует что угодно — холст во всю ширину, собственную сетку,
// внешний дизайн, привезённый навыком или сервисом.
//
// 🔒 ДВЕРЬ ЗАКРЫТА ПО УМОЛЧАНИЮ. Слой работает, только когда владелец включил
// `customDesign` в `DESIGN-CONFIG` (панель → «Дизайн»). Пока не включил, любая
// страница отсюда отвечает 404: не «пустой экран» и не «почти работает», а честное
// «такой страницы нет». Значение читается с диска при генерации — статика цела.
//
// 🔒 ЧТО ВЛАДЕЛЕЦ ТЕРЯЕТ, УВОДЯ СТРАНИЦУ СЮДА. Палитра из панели её больше не
// перекрашивает (переменные доступны, но никто их не применяет за него), меню и
// подвал не приходят, согласие на cookie не показывается, установка приложения не
// предлагается. Дальше страницу ведёт архитектор руками — это его зона
// ответственности, и она названа так владельцем.
//
// 🔒 ЧТО ОСТАЁТСЯ ВСЕГДА, потому что иначе страница перестаёт быть документом:
// `<html lang>`, метаданные, манифест и шрифт — они приходят из `[lang]/layout.tsx`.

import { notFound } from "next/navigation";
import { getDesignConfig } from "@/config/design-config";

export default function FreeLayer({ children }: { children: React.ReactNode }) {
  // Разрешение — не украшение: без него слоя не существует. Проверка стоит в
  // layout, а не в каждой странице, чтобы её нельзя было забыть на одной из них.
  if (!getDesignConfig().customDesign) notFound();

  return <>{children}</>;
}
