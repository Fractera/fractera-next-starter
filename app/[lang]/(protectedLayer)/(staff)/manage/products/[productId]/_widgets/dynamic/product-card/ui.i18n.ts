export type ProductCardUi = {
  /** Подпись строки с идентификатором. */
  colId: string
  /** Единственный отказ, который карточка показывает сама. */
  failed: string
}

const UI: Record<string, ProductCardUi> = {
  en: { colId: "ID", failed: "Could not do that. Try again." },
  ru: { colId: "Идентификатор", failed: "Не получилось. Повторите." },
  es: { colId: "ID", failed: "No se pudo. Inténtelo de nuevo." },
  fr: { colId: "ID", failed: "Échec. Réessayez." },
  it: { colId: "ID", failed: "Non è riuscito. Riprova." },
  de: { colId: "ID", failed: "Hat nicht geklappt. Erneut versuchen." },
  pt: { colId: "ID", failed: "Não deu certo. Tente de novo." },
  pl: { colId: "Identyfikator", failed: "Nie udało się. Spróbuj ponownie." },
  tr: { colId: "Kimlik", failed: "Olmadı. Tekrar deneyin." },
  nl: { colId: "ID", failed: "Het lukte niet. Probeer opnieuw." },
}

export function productCardUi(lang: string): ProductCardUi {
  return UI[lang] ?? UI[lang.slice(0, 2)] ?? UI.en
}
