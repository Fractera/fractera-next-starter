import { FLOW_COLOR, type ProtectedGroup } from "@/lib/flows"

// ПОЛОСА ПОТОКА — вертикальная лента у правого края с названием слоя прав.
//
// 🔒 ЗАЧЕМ. Четыре слоя показывают ОДНУ и ту же сущность, отличаясь тем, что в
// ней можно делать. Человек, переключившийся между вкладками, через минуту не
// помнит, в каком качестве он сейчас смотрит на товары, — и удивляется, что
// кнопки другие. Полоса отвечает на этот вопрос, не отнимая ни одного нажатия:
// она просто есть, всё время, одного цвета на весь поток.
//
// 🔒 ПОЧЕМУ ЭТО НЕ ЛОМАЕТ СТАТИКУ. Поток известен из АДРЕСА, а не из сессии:
// маршрут лежит в своей группе прав, значит слой определён на сборке. Полоса —
// серверный компонент без единого запроса: ни `auth()`, ни `cookies()`, ни
// `/api/me`. Она уезжает в предрендер вместе с заголовком страницы, и страница
// остаётся статической ровно настолько, насколько была.
//
// 🔒 ПОЧЕМУ СПРАВА И ПОЧЕМУ `fixed`. Слева у продукта живут меню и крошки —
// место занято. `fixed` держит ленту в поле зрения при прокрутке: смысл её в
// том, чтобы отвечать на вопрос в ЛЮБОЙ момент, а не только наверху страницы.
// На узком экране лента прячется: ширина там дороже, чем польза, а цветная точка
// в ящике аккаунта отвечает на тот же вопрос.
//
// ─────────────────────────────────────────────────────────────────────────────
// 🔒 В ПОКОЕ ЛЕНТА — ДВА ПИКСЕЛЯ, ПОЛНАЯ ШИРИНА ПРИХОДИТ ПО НАВЕДЕНИЮ
// (решение владельца 2026-08-25). Прежняя лента в 24 пикселя была постоянно
// развёрнута и **перекрывала правый край содержимого**: ни один макет защищённого
// слоя не отступает под неё, она просто лежит поверх.
//
// 🔒 ЧИСТЫЙ CSS, БЕЗ ОСТРОВКА. Наведение умеет сам браузер; островок ради него
// означал бы JavaScript на каждой защищённой странице в обмен ни на что — и
// превратил бы серверный компонент в клиентский, потеряв то, ради чего он писался
// серверным (см. второй закон выше).
//
// 🔒 ОБЛАСТЬ НАВЕДЕНИЯ ШИРЕ ВИДИМОЙ ПОЛОСЫ, И ЭТО ИСПОЛНЯЕТ ЗАКАЗ, А НЕ СПОРИТ С НИМ.
// Попасть мышью в два пикселя — задача на точность, а не действие; человек будет
// промахиваться и решит, что лента сломана. Поэтому наведение ловит ПРОЗРАЧНАЯ
// полоса в восемь пикселей — те самые «два-четыре пикселя от края» с запасом на
// дрожь руки, — а ВИДНО по-прежнему два.
//
// 🔒 ЧЕМ ЭТО ПЛАТИТСЯ, СКАЗАНО ЗДЕСЬ, А НЕ ОБНАРУЖИВАЕТСЯ ПОТОМ. `hover` не
// существует на сенсорном экране, поэтому на планшете шириной ≥768px подпись не
// раскроется никогда — остаётся ЦВЕТ, и он отвечает на тот же вопрос («в каком я
// слое»), просто без слова. Это осознанная деградация, а не недосмотр: чинить её
// островком означало бы вернуть JavaScript, от которого мы только что ушли.
export function FlowRail({ group, label }: { group: ProtectedGroup; label: string }) {
  const c = FLOW_COLOR[group]

  return (
    <div
      aria-hidden
      // 🔒 `w-2` — это ЛОВУШКА НАВЕДЕНИЯ: она прозрачна и не рисует ничего. Ширины
      // её не видно, поэтому «перекрыть содержимое» она не может; перехватить
      // нажатие тоже — восемь пикселей у самого края лежат за пределами раскладки.
      className="group fixed right-0 top-14 bottom-0 z-30 hidden w-2 select-none md:block"
    >
      <div
        // Раскрытие идёт ВЛЕВО от края: `right-0` держит ленту прижатой, растёт её
        // ширина. Иначе при раскрытии она сдвигалась бы и «прыгала» под курсором.
        //
        // `motion-reduce:transition-none` — по тому же правилу, по которому стоят
        // без движения секции каталога: у кого выключена анимация, лента просто
        // меняет ширину мгновенно.
        className={`absolute inset-y-0 right-0 w-0.5 overflow-hidden transition-[width] duration-200 ease-out group-hover:w-6 motion-reduce:transition-none ${c.bg}`}
      >
        {/* Текст повёрнут на 90°: вертикальная надпись читается сверху вниз, и
            именно так её ждёт глаз на боковой ленте.
            🔒 В ПОКОЕ ОН НЕ ПРОСТО ОБРЕЗАН, А ПРОЗРАЧЕН: обрезанная надпись в два
            пикселя выглядит как остаток буквы, то есть как поломка. */}
        <div className="flex h-full items-center justify-center opacity-0 transition-opacity duration-200 group-hover:opacity-100 motion-reduce:transition-none">
          <span
            className="whitespace-nowrap text-[10px] font-medium uppercase tracking-[0.2em] text-white"
            style={{ writingMode: "vertical-rl" }}
          >
            {label}
          </span>
        </div>
      </div>
    </div>
  )
}
