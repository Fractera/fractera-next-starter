// Манифест группы «О нас» для сканера верхнего меню.
//
// 🔒 БЕЗ ЭТОГО ФАЙЛА СТРАНИЦЫ В МЕНЮ НЕТ. Сканер (`lib/menu/group-menus.ts`)
// находит группу ТОЛЬКО по нему: страница при этом открывается по прямому
// адресу, но шапка о ней не знает — ни на одном развёртывании. Ровно так блог и
// каталог прожили в стартере без пунктов меню.
//
// 🔒 ЭТО КОД-УРОВНЕВОЕ УМОЛЧАНИЕ, А НЕ НАСТРОЙКА ВЛАДЕЛЬЦА. Панель пишет те же
// пункты в `APP-CONFIG/app-config.json`; тот файл лежит вне git. Пока ветки
// `nav.top` в нём нет, отвечает этот манифест — и свежий проект показывает «О
// нас» в шапке сразу, до того как владелец открыл панель. Как только владелец
// сохранит меню в панели, главным станет его список, а этот применяться
// перестанет.
//
// order: 30 — после «Продуктов» (10) и «Блога» (20): порядок в меню решает это
// число, а не порядок папок на диске.
//
// childrenAsDropdown: false — страница одна, разворачивать нечего. Кнопка ведёт
// прямо на неё.
//
// Подпись кнопки берётся из `_data/<язык>.ts` (поле `eyebrow`): «About us» и
// «О нас». Без него сканер назвал бы пункт именем папки — «About Us» — на всех
// языках сразу, включая русский.
//
// Папка лежит внутри `(footerPages)`, но скобочные группы для сканера прозрачны
// (`findGroupDirs` заходит внутрь них), поэтому пункт находится и адрес остаётся
// `/<язык>/about-us`.
//
// 🔒 ПОДВАЛ ТОЖЕ ЗДЕСЬ, А НЕ В `DEFAULT_FOOTER` — И РАЗНИЦА В ПЕРЕВОДЕ.
// Подвал складывает два источника: `defaultFooterGroups()` (список правовых
// страниц в `lib/menu/nav-config.ts`) и группы с диска, то есть этот файл.
// Первый берёт подпись из `APP-CONFIG.i18n`, а он на свежем проекте пуст —
// поэтому «Privacy» и «Cookies» стоят по-английски и в русском подвале.
// Манифест читает подпись из языковой ячейки, и «О нас» приходит на языке
// страницы. Дублирования нет: ссылка объявлена ровно в одном месте.
export const group = {
  slug: 'about-us',
  roles: "public",
  childrenAsDropdown: false,
  menus: {
    top: { enabled: true, order: 30 },
    footer: { enabled: true, order: 50 },
    left: { enabled: false, order: 10 },
    right: { enabled: false, order: 10 },
  },
}
