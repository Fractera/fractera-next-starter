import type { FooterPageCell } from '@/lib/pages/footer-page'

// Языковая ячейка страницы «О нас».
//
// 🔒 ЗАЧЕМ СОБСТВЕННЫЙ ТИП, ЕСЛИ ПОЛЯ ТЕ ЖЕ. Из-за одного поля — `eyebrow`.
// Сканер верхнего меню (`lib/menu/group-menus.ts`) берёт подпись кнопки из
// `_data/<язык>.ts` РОВНО по этому имени и разбирает файл как текст. Нет
// поля — кнопка называется именем папки («About») на всех языках сразу, в том
// числе на русском. Это ровно тот случай, который запрещает правило «видимый
// текст только через переводы».
//
// Ячейки страниц подвала обходятся без него потому, что их пункты живут в
// подвале, а тот подписи из ячеек не читает вовсе (`DEFAULT_FOOTER`).
export type AboutCell = FooterPageCell & {
  /** Подпись кнопки в верхнем меню. Не длиннее 12 знаков — полоса одна и горизонтальна. */
  eyebrow: string
}
