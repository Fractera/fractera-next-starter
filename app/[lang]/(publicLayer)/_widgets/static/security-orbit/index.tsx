import { securityOrbitUi } from "./ui.i18n"
import { SecurityStatic } from "./static"
import { SecuritySwap } from "./swap.client"

// ВИДЖЕТ «безопасность» — статическая разновидность, первая в проекте (шаг 521).
//
// 🔒 ЧЕМ ОН ОТЛИЧАЕТСЯ ОТ ПЯТИ ПРЕДЫДУЩИХ. Те динамические: спят, пока не нажмёшь,
// ходят в базу, рисуют пришедшее. Этот отрисован сразу и целиком — данных ему не
// нужно вовсе, он часть первого впечатления. Место жительства от этого не
// меняется: папка внутри своего маршрута, вид назван папкой `static/`.
//
// 🔒 СЛОВА РЕЗОЛВЯТСЯ ЗДЕСЬ, НА СЕРВЕРЕ, и уезжают внутрь пропсом. Клиентский
// файл, импортирующий словарь, увёз бы в браузер все его языки.
//
// Снаружи — только сквозное: примитивы `components/ui/*`, значки `lucide-react`,
// библиотека движения `motion` (и та лениво, после первого нажатия). Ни одного
// фрагмента виджета наверх не вынесено.
export function SecurityOrbit({ lang }: { lang: string }) {
  const ui = securityOrbitUi(lang)
  return (
    <SecuritySwap ui={ui}>
      <SecurityStatic ui={ui} />
    </SecuritySwap>
  )
}
