import { Frame, Orbit, Card } from "./parts"
import type { SecurityOrbitUi } from "./ui.i18n"

// СТАТИЧЕСКИЙ БЛИЗНЕЦ — то, что отдаёт сервер и что видит человек с выключенным
// JavaScript.
//
// 🔒 ЭТО НЕ ЗАПАСНОЙ ВАРИАНТ, А ОСНОВНОЙ. У донора анимация написана на `motion`,
// и в разметку уезжает `opacity:0` с ожиданием, что движение его снимет: без JS
// такой блок остаётся пустым местом. Закон проекта прямо обратный — приложение
// обязано работать с выключенным JavaScript, — поэтому первым рисуется покой:
// всё видно, ничто не ждёт скрипта.
//
// Анимированная версия приходит ПОСЛЕ первого нажатия и подменяет близнеца
// (`swap.client.tsx`). Геометрия у обеих одна и та же — она в `parts.tsx`.
export function SecurityStatic({ ui }: { ui: SecurityOrbitUi }) {
  return (
    <Frame
      ui={ui}
      orbit={() => <Orbit />}
      card={i => <Card card={ui.cards[i]} index={i} />}
    />
  )
}
