// Форматирование числа — ОДНО МЕСТО для близнеца и анимированной версии.
// Разошлись бы на первой же правке разделителя разрядов, и человек увидел бы
// два разных числа: одно до подмены, другое после.
//
// 🔒 ЛОКАЛЬ ЗАФИКСИРОВАНА ("en-US"), А НЕ ВЗЯТА У ОКРУЖЕНИЯ. Число — машинная
// величина (тот же закон, что у `value` в блоке `metrics`). У сервера и у
// браузера может быть разная локаль по умолчанию, и разный разделитель разрядов
// стал бы расхождением между серверной разметкой и гидратацией без единой
// правки кода — гидрация обязана видеть тот же текст, что напечатал сервер.
export function formatCount(n: number): string {
  return n.toLocaleString("en-US")
}
