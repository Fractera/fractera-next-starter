import { userCounterUi } from "./ui.i18n"
import { CounterStatic } from "./static"
import { CounterSwap } from "./swap.client"
import { formatCount } from "./format"

// ВИДЖЕТ «счётчик пользователей» — статическая разновидность, вторая в
// проекте (первая — `security-orbit`). Временная проверка по просьбе
// владельца: показать «сколько всего людей пользуется сервисом» — базовое
// значение, умноженное на случайное от 0 до 99, отсчёт от нуля за три
// секунды при попадании блока в поле зрения.
//
// 🔒 СЛУЧАЙНОЕ ЧИСЛО СЧИТАЕТСЯ РОВНО ОДИН РАЗ — НА СЕРВЕРЕ, ПРИ РЕНДЕРЕ
// СТРАНИЦЫ. Вызов `Math.random()` в серверном компоненте не делает маршрут
// динамическим сам по себе (в файле нет ни `cookies()`, ни `headers()`, ни
// `force-dynamic`) — он лишь решает, какое число запечётся в статическую
// разметку при сборке. Считать множитель в БРАУЗЕРЕ при каждой загрузке
// значило бы одно из двух: либо разъехаться с числом в подписи у человека без
// JavaScript (два разных числа на одной странице), либо тащить за собой
// динамику ради «нового» числа на каждый запрос — обе цены проект не платит
// (раздел CLAUDE.md «Статические страницы — и три способа их убить»).
//
// 🔒 BASE_USERS — ПЛЕЙСХОЛДЕР ЭТОЙ ВРЕМЕННОЙ ПРОВЕРКИ. Задаче нужно «базовое
// значение»; какое оно на самом деле — решение владельца. Значение живёт
// здесь константой и не заводит нового поля ни в одном из четырёх конфигов
// (закон CLAUDE.md «заводить новые поля нельзя»).
//
// 🔒 СЛОВА РЕЗОЛВЯТСЯ ЗДЕСЬ, НА СЕРВЕРЕ, и уезжают внутрь пропсом — тот же
// закон, что у `security-orbit`: клиентский файл, импортирующий словарь,
// увёз бы в браузер все его языки.
const BASE_USERS = 1240

export function UserCounter({ lang }: { lang: string }) {
  const ui = userCounterUi(lang)
  const multiplier = Math.floor(Math.random() * 100) // 0..99, дословно по просьбе владельца
  const value = BASE_USERS * multiplier
  const formatted = formatCount(value)
  const caption = ui.caption.replace("{count}", formatted)

  return (
    <CounterSwap value={value} formatted={formatted} caption={caption}>
      <CounterStatic formatted={formatted} caption={caption} />
    </CounterSwap>
  )
}
