import { PostBody } from '@/components/content-page/post-body'
import { homePage } from '../_data'

// Вход главной страницы.
//
// 🔒 БЫЛО 234 СТРОКИ ВЁРСТКИ, СТАЛО ЧЕТЫРЕ (шаг 508). Здесь лежала вся страница
// целиком: герой, ярлыки, четыре секции в рамках, свечение, ссылки на панель —
// и всё это вперемешку со словами из плоского словаря. Теперь содержимое живёт
// данными в языковых ячейках (`../_data`), а рисуют его секции — ровно тот же
// закон, по которому устроен пост блога.
//
// 🔒 КРОШЕК И ССЫЛКИ «НАЗАД» ЗДЕСЬ НЕТ НАМЕРЕННО. Главная не пользуется фабрикой
// `createContentPage`: та даёт хлебные крошки, оглавление и возврат на уровень
// выше — у корня сайта нет уровня выше, и крошка «Главная → Главная» была бы
// ложью. Общая с постом часть — архитектура ДАННЫХ, а не хром страницы.
export default async function Home({ lang }: { lang: string }) {
  const page = homePage(lang)

  return (
    <main data-app-column className="flex-1 px-6 py-20" lang={lang}>
      <div className="mx-auto max-w-3xl">
        <PostBody blocks={page.blocks} lang={lang} />
      </div>
    </main>
  )
}
