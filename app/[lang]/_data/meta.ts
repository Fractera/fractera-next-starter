import { getAppConfig } from '@/config/app-config'
import { getOgImagePath } from '@/config/app-config.defaults'

// Непереводимое главной — тот же файл, что у поста (`_data/meta.ts`, шаг 508).
//
// 🔒 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, ЕСЛИ ПОЛЕЙ ДВА. Он проводит границу: что переводится,
// а что нет. У поста здесь дата, теги и обложка; у главной — адрес и картинка
// для соцсетей. Пока такого файла не было, непереводимое главной размазывалось
// между маршрутом и настройками, и на вопрос «где у страницы обложка» ответа не
// существовало — а он должен быть одинаковым на всех поверхностях.

export const meta = {
  /** Путь без языка: у главной он пустой — `/` или `/<язык>`. */
  subPath: '',
  /**
   * Картинка для соцсетей. Берётся из настроек проекта, а не вписана здесь:
   * у каждого проекта она своя и меняется в панели без пересборки.
   * Не загрузили — пусто, и фабрика честно обойдётся без неё.
   */
  get ogImage(): string {
    return getOgImagePath(getAppConfig()) ?? ''
  },
}
