// 🔒 ЗАКАЗ ВЛАДЕЛЬЦА 2026-08-30, дословно: коды «должны быть подсвечены несколько
// более крупным шрифтом в[нутри] контейнера с фирменным цветом. То есть должны
// очень чётко отделяться от основного дизайна».
//
// 🔒 ЗАЧЕМ ЭТО НУЖНО, А НЕ ПРОСТО КРАСИВО. Каталог — рабочий инструмент: человек
// и агент выбирают по нему вид и потом называют его в задаче. Пока код набран
// тем же серым, что и объяснение под ним, взгляд его не находит, и вид называют
// по описанию — «тот, где меню слева». Метка возвращает каталогу назначение
// справочника: сначала видно ИМЯ, потом читается пояснение.
//
// 🔒 ОДИН КОМПОНЕНТ НА ДВА КАТАЛОГА. Их действительно два — админская страница
// образцов и раздел «блоки» в слое архитектора, — и они уже расходились: у одной
// код печатался как `kind: 'workspace'`, у другой просто `workspace`. Две копии
// метки разошлись бы снова, и разошлись бы молча.
//
// Цвет — токенами темы: `bg-primary` с парным `text-primary-foreground`.
// Пара обязательна, и её проверяет сторож секций: одиночный `bg-primary` с
// `text-foreground` читается только в одной теме из двух, и автор своей ошибки
// не увидит.
export function KindBadge({ code }: { code: string }) {
  return (
    <span
      data-kind-code={code}
      className="inline-flex items-center rounded-md bg-primary px-2.5 py-1 font-mono text-[length:var(--fs-body)] font-semibold tracking-tight text-primary-foreground"
    >
      {code}
    </span>
  )
}
