import { StaticImage } from '@/components/media/static-image.server'

// ОБЛОЖКА СТРАНИЦЫ — ПРИМИТИВ, А НЕ ВЁРСТКА ФАБРИКИ (шаг 542).
//
// 🔒 ПОЧЕМУ НЕ ВИД КАТАЛОГА. Обложку не выбирают в списке блоков: она появляется
// оттого, что у страницы есть `heroImage`, ровно как заголовок появляется
// оттого, что у страницы есть название. Заведи её видом — и в каталоге окажется
// вид, который автор не может поставить, а каталог обещает обратное.
//
// 🔒 ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПОЛЕ `PageHeader`. Внутри шапки обложка стала бы
// элементом контейнера с `gap-4`, и к её собственным `my-8` прибавилось бы ещё
// шестнадцать пикселей воздуха — на КАЖДОЙ странице с обложкой. Компенсировать
// это подобранными числами значит завести ту самую подгонку руками, ради
// избавления от которой примитивы и существуют.
//
// 🔒 `priority`, А НЕ ЛЕНИВАЯ ЗАГРУЗКА — и это отличает обложку от вида `figure`.
// Она стоит на первом экране и почти всегда является самым крупным элементом
// страницы: именно по нему поисковик меряет скорость её появления. У `figure`
// всё наоборот — иллюстрация внутри материала лежит ниже сгиба, и грузить её
// вперёд текста значит замедлять то, что человек читает первым.
export function PageCover({
  src,
  alt,
}: {
  src: string
  alt: string
}) {
  return (
    <figure className="my-8">
      <StaticImage
        src={src}
        alt={alt}
        priority
        sizes="(max-width: 768px) 100vw, 48rem"
        className="w-full h-auto rounded-2xl border border-border"
      />
    </figure>
  )
}
