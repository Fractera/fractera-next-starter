import type { ReactNode } from "react"
import { cn } from "@/lib/utils"

// ОБОЛОЧКА СТРАНИЦЫ — ОДНА НА ВЕСЬ САЙТ.
//
// 🔒 ЧТО ЭТО ЛЕЧИТ (2026-08-19, нашёл владелец: «блог выглядит чужим»). Шапку
// страницы уже свели к одному примитиву (`PageHeader`), а вот ОБОЛОЧКУ — `<main>`,
// ленту `data-app-column` и её воздух — каждая страница по-прежнему писала сама.
// Замер по дереву на момент правки:
//
//   шаблон материала   pt-content / pb-content   <article data-app-column>
//   каталог товаров    py-work                   <div data-app-column>
//   карточка товара    py-work                   <div data-app-column>
//   СПИСОК БЛОГА       py-content + gap-12       <div data-app-column>
//
// Три разных воздуха и два разных тега на четырёх публичных страницах. Глаз
// читает это ровно так, как сказал владелец: «другая оболочка, другие отступы».
//
// 🔒 ПОЧЕМУ ПРИМИТИВ, А НЕ ПРАВКА КЛАССОВ. Классы, подогнанные руками, совпадают
// ровно до следующей страницы: место, где принимается решение о воздухе, так и
// остаётся в каждом файле своё. Пока оболочка не названа одним компонентом,
// расхождение — не ошибка автора, а свойство кода.
//
// 🔒 НИЖНИЙ ВОЗДУХ ПОСТОЯНЕН, ВЕРХНИЙ — ДВА ЗНАЧЕНИЯ. Низ отделяет содержимое от
// подвала и обязан быть одинаковым везде. Верх зависит от того, есть ли у
// страницы шапка: под шапкой отмерен `--page-py-content`, а там, где заголовок
// печатает первый экран (лендинг) или где страница рабочая, стоит меньший
// `--page-py-work`. Третьего значения нет и заводить его нельзя — оно и есть тот
// самый способ, которым шкала перестаёт существовать.
//
// 🔒 ЗНАЧЕНИЯ ПЕРЕЧИСЛЕНЫ ЛИТЕРАЛАМИ, А НЕ СОБРАНЫ СТРОКОЙ. `pt-[var(--page-py-
// ${top})]` Tailwind не увидит: он сканирует исходники текстом и класса, которого
// в тексте нет, не создаёт. Такая запись собирается без ошибки и молча теряет
// отступ.

type Rhythm = "content" | "work"

const TOP_AIR: Record<Rhythm, string> = {
  content: "pt-[var(--page-py-content)]",
  work: "pt-[var(--page-py-work)]",
}

export type PageShellProps = {
  /** Верхний воздух ленты. `work` — рабочий экран или страница без шапки. */
  top?: Rhythm
  /**
   * Тег ленты. `article` — у страницы, которая ЦЕЛИКОМ является материалом
   * (пост, правовой документ); `div` — у списка, каталога, рабочего экрана.
   */
  columnAs?: "div" | "article"
  /** Внутренний ритм ленты (`flex flex-col gap-*` и т.п.). Ширина и воздух — не сюда. */
  className?: string
  /**
   * Разметка для поисковика (`application/ld+json`). Стоит ВНЕ ленты: она ничего
   * не занимает на экране, и внутри колонки с `gap` её пришлось бы каждый раз
   * проверять глазами.
   */
  jsonLd?: ReactNode
  /**
   * Первый экран — во всю ширину, ВНЕ ленты. Ширину задаёт родитель: пока секция
   * лежит внутри колонки, шире неё она не станет.
   */
  hero?: ReactNode
  /**
   * Сразу ЗА первым экраном, тоже во всю ширину и вне ленты (шаг 521).
   *
   * 🔒 ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОТ, А НЕ НОВЫЙ ВИД БЛОКА. Сюда встаёт ВИДЖЕТ — вещь,
   * принадлежащая одному маршруту. Видом блока он быть не может: каталог видов
   * закрыт, и у каждого вида обязан быть образец на служебной странице, то есть
   * платформа начала бы импортировать код маршрута. Слот оставляет виджет
   * собственностью маршрута: маршрут его строит, маршрут же и передаёт.
   */
  afterHero?: ReactNode
  /** Завершающая секция — тоже во всю ширину, ниже ленты. */
  /** Разметка ПОСЛЕ тела и до завершающей секции (69). */
  afterBody?: ReactNode
  outro?: ReactNode
  children: ReactNode
}

export function PageShell({
  top = "content",
  columnAs: Column = "div",
  className,
  jsonLd,
  hero,
  afterHero,
  afterBody,
  outro,
  children,
}: PageShellProps) {
  return (
    <main className="min-h-screen bg-background text-foreground">
      {jsonLd}
      {hero}
      {afterHero}
      <Column
        data-app-column
        className={cn("px-6 pb-[var(--page-py-content)]", TOP_AIR[top], className)}
      >
        {children}
      </Column>
      {afterBody}
      {outro}
    </main>
  )
}
