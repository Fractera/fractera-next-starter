"use client"

// ССЫЛКА НА ЧАТ С ИИ-АГЕНТОМ В ПОДВАЛЕ — АДРЕС ИЗ ДВУХ ИСТОЧНИКОВ (шаг 96).
//
// 🔒 БЛИЗНЕЦ `admin-link.client.tsx`, И ЭТО НАМЕРЕННО. Владелец 2026-08-29 спросил про кнопку
// панели: «почему у меня на старте, когда я нахожусь в IP-режиме, отсутствует кнопка перейти в
// админпанель?» — тогда `{adminUrl && …}` прятал ссылку на свежем сервере, где `APP-CONFIG`
// ещё пуст. Решение: сервер даёт адрес из настроек, а без них островок выводит его из адреса
// окна. Ни один источник не выдумывает — оба считают.
//
// ✗ Оплачено повторно 2026-09-03: у кнопки чата стояло то же `{chatUrl && …}`, и на новом
// сервере её не было вовсе. Тот же вопрос владельца, тот же день установки, тот же ответ —
// значит закон должен жить в ОБЩЕМ образце, а не в памяти того, кто пишет следующую кнопку.

import { useEffect, useState } from "react"
import { Bot } from "lucide-react"
import { chatBase } from "@/lib/runtime-urls"
import { buttonVariants } from "@/components/ui/button"

// 🔒 ДВА ИСТОЧНИКА, И НИ ОДИН НЕ УГАДЫВАЕТ. Сервер даёт адрес из настроек, когда они есть, —
// тогда ссылка стоит уже в статическом HTML и работает без скриптов. Настроек нет — островок
// после гидратации выводит адрес из СОБСТВЕННОГО адреса окна: IP → `<хост>:3600`, домен →
// `chat.<апекс>`. Тот же расчёт, которым пользуется весь клиентский код (`lib/runtime-urls.ts`).
//
// 🔒 ЗАКОН «ВЫДУМАННЫЙ АДРЕС ХУЖЕ ОТСУТСТВУЮЩЕГО» НЕ НАРУШЕН: он запрещает ВЫДУМЫВАТЬ, а не
// ВЫЧИСЛЯТЬ. Чат живёт на своём порту у той же машины — это факт развёртывания, а не догадка.
//
// 🔒 ПОДВАЛ ПО-ПРЕЖНЕМУ НЕ ЧИТАЕТ СЕССИЮ И НЕ УХОДИТ В ДИНАМИКУ: островок смотрит на адресную
// строку и ничего не спрашивает у сервера.

export function ChatLink({
  /** Адрес, посчитанный сервером из настроек. Пусто — считает островок. */
  href,
  label,
}: {
  href: string
  label: string
}) {
  const [fallback, setFallback] = useState("")

  useEffect(() => {
    if (!href) setFallback(chatBase())
  }, [href])

  const target = href || fallback
  if (!target) return null

  return (
    <a
      href={target}
      // 🔒 ЧАТ ОТКРЫВАЕТСЯ В НОВОЙ ВКЛАДКЕ, как и панель: он живёт на другом хосте, и
      // это уход с сайта, а не переход по нему. `noopener` обязателен рядом с
      // `_blank` — без него открытая страница получает ссылку на окно-родитель.
      target="_blank"
      rel="nofollow noopener noreferrer"
      data-chat-link={href ? "from-settings" : "from-window"}
      className={buttonVariants({ variant: "ghost", size: "sm" }) + " gap-1.5 text-muted-foreground hover:text-foreground"}
    >
      <Bot className="hidden size-3.5 sm:inline-block" />
      {label}
    </a>
  )
}
