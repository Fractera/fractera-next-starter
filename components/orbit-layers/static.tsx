import { Frame, Orbit, Card, type OrbitLayersUi } from "./parts"

// СТАТИЧЕСКИЙ БЛИЗНЕЦ — то, что отдаёт сервер и что видит человек с выключенным
// JavaScript.
//
// 🔒 ЭТО НЕ ЗАПАСНОЙ ВАРИАНТ, А ОСНОВНОЙ. У источника анимация написана на
// `motion`, и в разметку уезжает `opacity:0` с ожиданием, что движение его
// снимет: без JS такой блок остаётся пустым местом. Закон проекта прямо обратный
// — страница обязана работать с выключенным JavaScript, — поэтому первым
// рисуется покой: всё видно, ничто не ждёт скрипта.
//
// Анимированная версия приходит ПОСЛЕ пробуждения и подменяет близнеца
// (`swap.client.tsx`). Геометрия у обеих одна и та же — она в `parts.tsx`.
export function OrbitLayersStatic({ ui }: { ui: OrbitLayersUi }) {
  return (
    <Frame
      ui={ui}
      orbit={() => <Orbit core={ui.core} />}
      card={i => <Card card={ui.cards[i]} index={i} />}
    />
  )
}
