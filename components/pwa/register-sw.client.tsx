'use client'

// Регистрация сервис-воркера — и его СНЯТИЕ (шаг 504, выключатель 2026-08-13).
//
// Островок без единого слова: интерфейса у него нет, поэтому и перевода не
// нужно, и в любом языке он работает одинаково. Всё видимое, что даёт установку,
// рисует браузер или соседний `install-prompt`.
//
// 🔒 ГЛАВНОЕ ЗДЕСЬ — ВЕТКА `enabled === false`, А НЕ РЕГИСТРАЦИЯ.
//
// Воркер, однажды установленный посетителю, живёт на ЕГО устройстве и переживает
// любые наши правки: перестать его отдавать — не значит его выключить. Владелец
// снимает галочку в панели, у себя видит, что всё в порядке, а у тысячи людей
// продолжает работать код, который он отключил, — и снять его они не могут,
// потому что не знают о его существовании.
//
// Поэтому выключатель работает В ОБЕ СТОРОНЫ: выключенный режим не просто «не
// регистрируем», а активно снимает регистрацию и стирает кеши. Выключатель,
// который умеет только включать, — это не выключатель.
//
// Регистрация идёт ПОСЛЕ загрузки страницы: воркер не должен соревноваться за
// сеть с содержимым, ради которого пришёл посетитель.
//
// Работает только в защищённом контексте (https или localhost) — по закону
// браузера. В режиме без домена сайт живёт по http, воркера там не будет, и это
// правильная деградация: приложение остаётся полностью рабочим.

import { useEffect } from 'react'

export function RegisterServiceWorker({ enabled }: { enabled: boolean }) {
  useEffect(() => {
    if (typeof navigator === 'undefined' || !('serviceWorker' in navigator)) return

    // Режим выключен — убираем следы с устройства. Делаем это ВСЕГДА, а не
    // только в защищённом контексте: снимать надо и там, где регистрировать было
    // нельзя, иначе останется воркер, поставленный когда-то по https.
    if (!enabled) {
      navigator.serviceWorker
        .getRegistrations()
        .then(regs => Promise.all(regs.map(r => r.unregister())))
        .then(async () => {
          // Кеши переживают снятие регистрации: сам по себе `unregister` их не
          // трогает, и на устройстве остались бы мегабайты чужого мусора.
          if (typeof caches === 'undefined') return
          const keys = await caches.keys()
          await Promise.all(keys.filter(k => k.startsWith('pages-') || k.startsWith('assets-')).map(k => caches.delete(k)))
        })
        .catch(() => {
          /* браузер отказал — не повод ломать страницу */
        })
      return
    }

    if (!window.isSecureContext) return

    const register = () => {
      navigator.serviceWorker.register('/sw.js').catch(() => {
        // Отказ регистрации не имеет права ничего ломать: сайт полноценно
        // работает и без воркера, тот даёт только офлайн и быстрое повторное
        // открытие.
      })
    }

    if (document.readyState === 'complete') register()
    else {
      window.addEventListener('load', register)
      return () => window.removeEventListener('load', register)
    }
  }, [enabled])

  return null
}
