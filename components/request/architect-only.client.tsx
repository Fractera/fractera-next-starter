"use client"

import { useEffect, useState } from "react"
import type { ReactNode } from "react"
import { ARCHITECT_LAYER_ROLES } from "@/lib/roles"

// ПОКАЗАТЬ ДЕТЕЙ ТОЛЬКО РОЛИ СЛОЯ — БЕЗ ПОТЕРИ СТАТИКИ (шаг 69, 2026-08-31).
//
// 🔒 ВОПРОС ВЛАДЕЛЬЦА, КОТОРЫЙ И РОДИЛ ЭТОТ ФАЙЛ: «нужно принять островок только
// если страница в режиме архитектора — можно это сделать, чтобы не потерять
// статику?». Можно, и способ ровно один.
//
// 🔒 СЕРВЕР НЕ СПРАШИВАЕТ СЕССИЮ, СПРАШИВАЕТ БРАУЗЕР. Страница остаётся
// полностью статической: HTML одинаков для всех, предрендерен на сборке и уходит
// в поиск. Роль выясняется ПОСЛЕ гидратации, одним запросом к `/api/me`.
// ✗ Одна строка с `cookies()` на странице сделала бы динамическим весь публичный
// слой — это записано законом и оплачено прежними правовыми страницами, где тело
// грузилось из рантайма и для поиска почти не существовало.
//
// 🔒 ПОСТОРОННИЙ НЕ ВИДИТ НИЧЕГО, И ЭТО НЕ ДЕРЖИТСЯ НА ЭТОМ ФАЙЛЕ. Дверь заявки
// закрыта теми же ролями (`api/architect/pre-step`): даже нарисуй кто-нибудь эту
// кнопку себе руками, заявка не создастся. Здесь решается ВИДИМОСТЬ, а не доступ —
// тот же порядок, что у ссылок слоя в подвале.
//
// 🔒 ЗАПРОС ДЕШЕВЛЕ, ЧЕМ КАЖЕТСЯ, И ЖИВЁТ НЕДОЛГО. Обёртка стоит только на
// НЕЗАПОЛНЕННОЙ странице — она часть заглушки. Владелец заменил текст своим:
// исчезли и заглушка, и кнопка, и этот запрос. Готовый сайт не платит ничем.
export function ArchitectOnly({ children }: { children: ReactNode }) {
  const [allowed, setAllowed] = useState(false)

  useEffect(() => {
    let alive = true
    fetch("/api/me", { credentials: "include" })
      .then(r => (r.ok ? r.json() : null))
      .then((s: { roles?: string[] } | null) => {
        if (!alive) return
        const roles = s?.roles ?? []
        setAllowed(roles.some(r => (ARCHITECT_LAYER_ROLES as readonly string[]).includes(r)))
      })
      // Молчим намеренно: не ответившая дверь означает «прав не подтвердили»,
      // а не «случилась беда». Сообщать посетителю об этом нечего.
      .catch(() => {})
    return () => {
      alive = false
    }
  }, [])

  if (!allowed) return null
  return <>{children}</>
}
