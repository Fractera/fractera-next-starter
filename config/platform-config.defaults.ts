/**
 * Что лежит В ФАЙЛЕ на диске — не то же самое, что видит вызывающий.
 *
 * 🔒 РАЗЛИЧИЕ ВАЖНОЕ, И ОНО ЕДИНСТВЕННОЕ СРЕДИ ЧЕТЫРЁХ КОНФИГОВ. Файл несёт
 * только решения владельца: тронутые выключатели и режим маршрутизации. Читатель
 * же отдаёт ПОЛНУЮ картину — значение каждой возможности плюс отдельный ответ на
 * вопрос «владелец высказался или это умолчание». Схема (`schema.json`) описывает
 * файл, потому что проверять на чтении можно только то, что действительно лежит
 * на диске.
 *
 * `instructions` пишет панель: это выключатели документов корпуса. Приложение их
 * не читает — они адресованы агенту, — но объявить поле обязано, иначе проверка
 * файла считала бы решение владельца посторонним ключом.
 */
export type PlatformConfigFile = {
  features?: Partial<Record<FeatureKey, boolean>>;
  /** Два исторических имени одного решения — оба читаются. */
  routingMode?: string;
  parallelRouting?: boolean;
  /**
   * Как ведётся работа над проектом (панель, «Режим разработки»).
   *
   * Решает ровно одно: обязательны ли подтверждённый кейс и открытый шаг перед
   * работой. Технические законы проекта от режима не зависят.
   */
  developmentMode?: "classic" | "steps" | "cases";
  /** Набор документов, которые читает агент; ключи задаёт панель. */
  instructions?: Record<string, boolean>;
  /** Снимок набора документов до включения мастер-режима. */
  instructionsSnapshot?: Record<string, boolean> | null;
  /** Команды-активаторы документов-способностей. */
  commands?: Record<string, unknown>;
};

/** Ненастроенный проект: файла нет, решений нет. */
export const DEFAULT_PLATFORM_CONFIG_FILE: PlatformConfigFile = {};

/** Что получает вызывающий — полная картина, а не сырьё файла. */
export type PlatformConfig = {
  features: Record<FeatureKey, boolean>;
  /**
   * Решал ли владелец судьбу возможности САМ.
   *
   * 🔒 ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ `features`. «Выключено по умолчанию» и «владелец
   * выключил» — разные вещи, и путать их значит ломать работающие серверы.
   * Авторизация до этого механизма жила сборочной переменной; будь у нас только
   * `features.auth === false`, каждый такой сервер молча потерял бы кнопку входа
   * при первом же развёртывании. Поэтому запасное значение применяется, ПОКА
   * владелец не высказался, и перестаёт — как только он тронул выключатель.
   */
  explicit: Record<FeatureKey, boolean>;
  /** Параллельная маршрутизация — читается двумя историческими именами. */
  parallel: boolean;
};
