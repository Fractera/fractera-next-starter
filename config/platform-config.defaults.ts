/**
 * Что лежит В ФАЙЛЕ на диске — не то же самое, что видит вызывающий.
 *
 * 🔒 РАЗЛИЧИЕ ВАЖНОЕ, И ОНО ЕДИНСТВЕННОЕ СРЕДИ ЧЕТЫРЁХ КОНФИГОВ. Файл несёт
 * только решения владельца: тронутые выключатели и режим маршрутизации. Читатель
 * же отдаёт ПОЛНУЮ картину — значение каждой возможности плюс отдельный ответ на
 * вопрос «владелец высказался или это умолчание». Схема (`schema.json`) описывает
 * файл, потому что проверять на чтении можно только то, что действительно лежит
 * на диске.
 *
 * `instructions` пишет панель: это выключатели документов корпуса. Приложение их
 * не читает — они адресованы агенту, — но объявить поле обязано, иначе проверка
 * файла считала бы решение владельца посторонним ключом.
 */
export type PlatformConfigFile = {
  features?: Partial<Record<FeatureKey, boolean>>;
  /** Два исторических имени одного решения — оба читаются. */
  routingMode?: string;
  parallelRouting?: boolean;
  /**
   * Как ведётся работа над проектом (панель, «Режим разработки»).
   *
   * Решает ровно одно: обязательны ли подтверждённый кейс и открытый шаг перед
   * работой. Технические законы проекта от режима не зависят.
   *
   * `migration` — четвёртый режим (шаг 533): очередь шагов рождается не из
   * подтверждённых кейсов, а из чужого кода, который уже написан.
   */
  developmentMode?: "classic" | "steps" | "cases" | "migration";
  /**
   * Стратегия автоматизации: `claude` — Claude Agent SDK, `openai` — ручной
   * конвейер на AI SDK с моделями OpenAI (шаг 112).
   *
   * 🔒 ИМЯ РЕЖИМА `claude`, А НЕ `cloud`: продукт называется **Claude Agent SDK**
   * (`https://code.claude.com/docs/en/agent-sdk/overview`). Поправка владельца
   * 2026-09-04 — «Cloud Agent SDK incorrect»; «Cloud» был артефактом распознавания.
   */
  automationMode?: "claude" | "openai";
  /**
   * Откуда читать чужой проект при переезде (панель, «Переезд на Fractera»).
   *
   * `repository` — владелец назвал адрес, агент читает клон; `local` — проект
   * лежит у владельца на машине, и разбор идёт там же, а сюда приезжают уже
   * дерево замысла и очередь шагов. Приложение это поле не читает: оно
   * адресовано агенту, как и `instructions`.
   */
  migration?: {
    source?: "repository" | "local";
    repositoryUrl?: string;
    /** Путь к папке на машине владельца. Сервер туда не ходит — это адрес для агента, который работает у владельца. */
    localPath?: string;
    declaredAt?: string;
  };
  /**
   * Какие области раскладки включены в параллельном режиме (шаг 31-12).
   *
   * 🔒 КЛЮЧ БЫЛ БЕЗЫМЯННЫМ, ХОТЯ ПИСАЛСЯ ДАВНО. Панель управления сохраняет сюда
   * `slots` с восьмью булевыми значениями (`ARCHITECTURE-PARALLEL-ROUTING.md`),
   * а ни тип, ни схема этого не знали: ключ проходил только потому, что схема
   * `looseObject`. Незнакомый ключ переживает проверку молча ровно до того дня,
   * когда кто-нибудь сделает схему строгой, — и тогда раскладка исчезнет у всех
   * серверов разом, без единого сообщения.
   *
   * 🔒 ОТСУТСТВИЕ КЛЮЧА — ЭТО НЕ «ВСЁ ВЫКЛЮЧЕНО». В стандартном режиме `slots` в
   * файле нет вовсе, и тогда действует набор по умолчанию: шапка, центр, подвал.
   */
  slots?: Record<string, boolean>;
  /** Набор документов, которые читает агент; ключи задаёт панель. */
  instructions?: Record<string, boolean>;
  /** Снимок набора документов до включения мастер-режима. */
  instructionsSnapshot?: Record<string, boolean> | null;
  /** Команды-активаторы документов-способностей. */
  commands?: Record<string, unknown>;
};

