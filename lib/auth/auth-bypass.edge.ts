// 🔒 ГРУБЫЙ ВАРИАНТ ПРАВИЛА — ТОЛЬКО ДЛЯ `proxy.ts` (шаг 520, 2026-08-20).
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Настоящее правило (`auth-bypass.ts`) читает флаг режима из
// файла окружения, потому что копия в памяти процесса умеет устареть и однажды
// открыла весь контур интернету. Но `proxy.ts` исполняется в среде Edge, где
// `node:fs` не существует: импорт файловой версии туда просто не соберётся.
//
// ПОЧЕМУ ЭТО НЕ ДЫРА. Прокси решает грубую задачу — пускать ли запрос дальше по
// маршруту. Решение «кто ты» принимает серверный слой: `getSession()` и
// `require-role` берут флаг ИЗ ФАЙЛА. Поэтому устаревшее `true` здесь способно
// лишь пропустить запрос к обработчику, который сам ответит 401, а не выдать
// личность. Обратный случай — устаревшее `false` в IP-режиме — даёт лишний 401 на
// онбординге: неприятно, но безопасно.
//
// 🚫 НЕ ИМПОРТИРОВАТЬ ЭТОТ ФАЙЛ НИГДЕ, КРОМЕ `proxy.ts`. Любое место, где решается
// доступ по существу, обязано брать `shouldBypassAuth` из `auth-bypass.ts`.
export function shouldBypassAuthEdge(): boolean {
  return process.env.NODE_ENV === "development"
      || process.env.FRACTERA_IP_NODOMAIN_MODE === "true";
}
