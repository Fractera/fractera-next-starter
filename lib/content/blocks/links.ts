// Ссылки внутри материала — ОДНО место, где решается их судьба (шаг 507).
//
// Раньше об этом знал только `inline.tsx`, разбиравший ссылки в прозе, и оба
// его решения были неверны в проекте клиента:
//
// 1. «Свой домен» был записан как `fractera.ai`. То есть на сайте клиента вес
//    без ограничений уходил домену ПЛАТФОРМЫ, а собственный домен клиента
//    считался чужим и получал `nofollow`. Идентичность обязана приходить из
//    настроек (`CONTENT-ENGINE.md` §6), и это правило движок нарушал первым.
//
// 2. Внутренняя ссылка на корень записывается как `/ru` — но в одноязычном
//    режиме `proxy.ts` снимает языковой сегмент, и такой адрес отвечает 301.
//    Ссылка на главную из каждой статьи превращалась в редирект; тот же случай
//    уже был вылечен для канонических адресов в `lib/seo/alternates.ts`, а для
//    ссылок в тексте — нет.
//
// Кнопка (`cta`) ходит по тем же законам, поэтому решение живёт здесь, а не в
// одном из рендереров.

import { SINGLE_LANG_MODE } from "@/config/translations/translations.config"
import { brand } from "@/lib/brand"

/** Внутренняя ссылка на корень сайта на языке ячейки: `/ru`, `/en`. */
export const ROOT_LINK = /^\/([a-z]{2})$/

/**
 * ЧЕТВЁРТАЯ ЗАКОННАЯ ФОРМА — ССЫЛКА НА СВОЮ ЖЕ СТРАНИЦУ: `/ru/about-us`
 * (заведена 2026-08-21, по требованию владельца описать перелинковку).
 *
 * 🔒 ЗАЧЕМ ОНА ПОНАДОБИЛАСЬ. До сегодня в материале была законна ровно ОДНА
 * внутренняя ссылка — на корень. То есть перелинковки, ради которой страницы и
 * связывают между собой, в движке не существовало вовсе: сослаться из статьи на
 * «О нас» было нечем. Обнаружено прогоном навыков — агент честно не поставил
 * ссылку и назвал причину, вместо того чтобы обойти правило.
 *
 * 🔒 ПОЧЕМУ ЗАПРЕТ ОТНОСИТЕЛЬНЫХ ССЫЛОК ПРИ ЭТОМ ОСТАЁТСЯ В СИЛЕ. Он написан по
 * настоящей причине: материал ПУТЕШЕСТВУЕТ между проектами, и `/pricing` в чужом
 * проекте означает другую страницу либо никакую. Поэтому форма разрешена не
 * молча: `check:content` проверяет, что маршрут с таким адресом СУЩЕСТВУЕТ в
 * этом проекте. Приехал материал со ссылкой на страницу, которой здесь нет, —
 * сборка отказывает и называет и статью, и адрес. Громкий отказ здесь дешевле
 * тихой ссылки в никуда: вторую находит посетитель, первую — тот, кто её принёс.
 *
 * Подпись у такой ссылки ЛЮБАЯ, в отличие от корневой: `%SITE%` подставляет имя
 * сайта, а имя страницы — это её название, и оно принадлежит материалу.
 */
export const PAGE_LINK = /^\/([a-z]{2})(\/[a-z0-9][a-z0-9/-]*)$/

/** Подпись, которую заменяет название сайта на языке ссылки. */
export const SITE_TOKEN = "%SITE%"

/** Хост из адреса сайта в настройках; пусто, если адрес ещё не задан. */
function ownHost(): string {
  try {
    const url = brand().siteUrl
    return url ? new URL(url).host.replace(/^www\./, "") : ""
  } catch {
    return ""
  }
}

/**
 * Ссылка ведёт на СОБСТВЕННЫЙ домен проекта? Тогда `nofollow` не ставится: вес
 * внутри своего сайта отдавать некому. Адрес сайта не задан — считаем чужим:
 * ошибиться в сторону осторожности дешевле.
 */
export function isOwnDomain(href: string): boolean {
  const host = ownHost()
  if (!host) return false
  try {
    return new URL(href).host.replace(/^www\./, "") === host
  } catch {
    return false
  }
}

/**
 * Адрес корневой ссылки с учётом одноязычного режима: там языкового сегмента в
 * публичных адресах нет, и `/en` отвечает редиректом. Не корневая ссылка —
 * возвращается как есть.
 */
export function resolveRootHref(href: string): string {
  if (!SINGLE_LANG_MODE) return href
  if (ROOT_LINK.test(href)) return "/"
  // Ссылка на свою страницу: в одноязычном режиме языкового сегмента в публичных
  // адресах нет, и `/en/about-us` отвечал бы 301 — тот же дефект, что был у
  // корневой ссылки, только на каждой странице материала.
  const page = href.match(PAGE_LINK)
  return page ? page[2] : href
}

/** Атрибуты внешней ссылки; для внутренней — ничего (та же вкладка, без rel). */
export function linkAttrs(href: string): { target?: string; rel?: string } {
  if (!/^https?:/.test(href)) return {}
  return {
    target: "_blank",
    rel: isOwnDomain(href) ? "noopener noreferrer" : "noopener noreferrer nofollow",
  }
}

/**
 * Раскрыть ссылки материала в ГОТОВЫЙ markdown — для машинной версии страницы.
 *
 * 🔒 ЗАЧЕМ ЭТО ПОНАДОБИЛОСЬ (найдено владельцем 2026-08-17). Машинная версия
 * собиралась из тех же блоков и переносила инлайновую разметку «как есть» — на
 * том основании, что `**жирный**` и `[метка](адрес)` уже markdown. Для ссылок
 * это оказалось неверно: `[%SITE%](/en)` — не markdown, а СОГЛАШЕНИЕ проекта,
 * которое раскрывает рендерер. Машина получала страницу, где вместо названия
 * сайта стоит `%SITE%`, а адрес ведёт в никуда: относительный путь без хоста
 * из файла, скачанного отдельно от сайта, не разрешается ни во что.
 *
 * То есть на каждой странице подвала ровно та ссылка, ради которой правило
 * `%SITE%` и придумано — «этот сайт называется так и живёт здесь», — до машины
 * не доезжала. Три страницы жили так с шага 505.
 *
 * Делается ДВЕ подстановки, и обе нужны:
 *   1. подпись `%SITE%` → название сайта на языке ссылки (как в HTML);
 *   2. корневой адрес `/en` → АБСОЛЮТНЫЙ. В HTML относительный адрес верен —
 *      его разрешает браузер от текущего документа; в markdown разрешать
 *      неоткуда, и абсолютный — единственная форма, которая работает.
 *
 * Адрес сайта не задан (владелец не сохранял настройки) — оставляем
 * относительный: выдуманный хост хуже отсутствующего.
 */
export function resolveMarkdownLinks(text: string, siteName: string): string {
  const origin = brand().siteUrl.replace(/\/$/, "")
  // Обе внутренние формы: корень (`/ru`) и своя страница (`/ru/about-us`).
  // Машинной версии нужен АБСОЛЮТНЫЙ адрес у обеих — файл скачивают отдельно от
  // сайта, и относительный путь в нём не разрешается ни во что.
  return text.replace(/\[([^\]]+)\]\((\/[a-z]{2}(?:\/[a-z0-9][a-z0-9/-]*)?)\)/g, (whole, label: string, href: string) => {
    const isRoot = ROOT_LINK.test(href)
    if (isRoot && label.trim() !== SITE_TOKEN) return whole
    if (!isRoot && !PAGE_LINK.test(href)) return whole
    const target = resolveRootHref(href)
    return `[${isRoot ? siteName : label}](${origin ? origin + target : target})`
  })
}
