import type { ReactNode } from 'react'
import type { Block } from './types'
import type { PostBodyUi } from '@/lib/content/post-body-ui'
import type { SectionCtx } from '@/sections/contract'
import { activeSet } from '@/sections'

// ─────────────────────────────────────────────────────────────────────────────
// Диспетчер блоков. С шага 508 он НЕ содержит ни одного рендерера: рисование
// переехало в слой секций (`sections/<дизайн>/blocks/<вид>.server.tsx`, один вид
// — один файл), а здесь осталась только раздача блока тому, кто его рисует.
//
// 🔒 ЗАЧЕМ ПЕРЕЕХАЛО. Две причины, и обе — не про красоту.
//
// 1. РАЗМЕР. Правило проекта: функциональный компонент не длиннее 200 строк.
//    Здесь их было 263 — шестнадцать маленьких компонентов, слипшихся в один
//    файл, потому что им негде было лежать порознь. В раскладке «файл на вид»
//    каждый занимает 10–50 строк, и лимит перестаёт быть требованием, которое
//    надо помнить: он становится следствием того, как лежит код.
//
// 2. ДИЗАЙНЫ. Пользователь вправе привести свой набор секций и переписать в нём
//    проект. Пока все рендереры лежат в одном файле платформы, «свой дизайн»
//    означает правку нашего файла — то есть форк. Теперь это своя папка.
//
// 🔒 ЧТО ОСТАЛОСЬ ЗДЕСЬ И ПОЧЕМУ. Обход блоков, ключи и рекурсия контейнеров —
// это механизм, а не оформление: он одинаков при любом дизайне. Отдай его
// дизайну — и каждый новый набор пришлось бы заново учить нумеровать ключи.
//
// Внешние имена (`renderBlock`, `renderBlocks`, `BlockRenderCtx`) сохранены
// дословно: переезд не имеет права задеть тех, кто ими пользуется.
// ─────────────────────────────────────────────────────────────────────────────

/** Совместимое имя контекста; форма объявлена договором дизайна. */
export type BlockRenderCtx = SectionCtx

/**
 * Нарисовать один блок.
 *
 * 🔒 НЕПОКРЫТЫЙ ВИД — ПУСТОЕ МЕСТО, А НЕ ПАДЕНИЕ И НЕ ЧУЖОЙ ПОЧЕРК. Дизайн не
 * обязан покрывать все виды (`sections/contract.ts`). Если рендерера нет:
 * страница не падает — уронить сайт клиента из-за одной секции несоразмерно; и
 * блок не подставляется молча из набора по умолчанию — тихая подстановка даёт
 * страницу в двух почерках и впечатление законченного дизайна там, где он
 * наполовину не написан. Что делать с непокрытым видом, решает манифест
 * (`inherits`), а `npm run read:sections` печатает разницу как задачу.
 */
export function renderBlock(block: Block, ctx: BlockRenderCtx): ReactNode {
  const render = activeSet()[block.kind] as ((b: Block, c: BlockRenderCtx) => ReactNode) | undefined
  return render ? render(block, ctx) : null
}

/**
 * Нарисовать список блоков по порядку. `keyPrefix` держит ключи уникальными
 * между уровнями вложенности (верхний уровень — `blk`).
 */
export function renderBlocks(
  blocks: Block[],
  lang: string,
  ui: PostBodyUi,
  keyPrefix = 'blk',
): ReactNode[] {
  return blocks.map((b, i) =>
    renderBlock(b, { lang, ui, key: `${keyPrefix}-${i}`, renderBlocks }),
  )
}
