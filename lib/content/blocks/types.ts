/**
 * Пункт меню или вкладки рабочего экрана.
 *
 * `href` необязателен намеренно — см. закон у вида `workspace`.
 */
export type WorkspaceItem = { label: string; href?: string; active?: boolean }

/**
 * Цветная карточка рабочего экрана.
 *
 * 🔒 ТОНОВ ТРИ, И ОНИ РАЗЛИЧАЮТСЯ ЖАНРОМ, А НЕ ГРОМКОСТЬЮ. Те же три, что уже
 * работают в слое архитектора: `recommended` (зелёный) СОВЕТУЕТ и обязан
 * выглядеть приглашением · `advice` (жёлтый) называет ЦЕНУ решения до того, как
 * его приняли, и остаётся верным навсегда · `warning` (красный) сообщает
 * СОСТОЯНИЕ системы прямо сейчас и исчезнет, когда состояние изменится.
 * Два одинаково окрашенных блока подряд человек читает как один длинный текст и
 * второй пропускает.
 */
export type WorkspaceNote = { tone: 'recommended' | 'advice' | 'warning'; title: string; text: string }
