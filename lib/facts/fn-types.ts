// ОПИСАННАЯ ФУНКЦИЯ ПРИЗНАКА — шестая, необязательная часть записи (81-8).
//
// 🔒 ТРЕБОВАНИЕ ВЛАДЕЛЬЦА 2026-09-01: «если пользователь будет размышлять о том,
// какая сейчас погода, или о том, какой курс акции, то данная функция должна
// уметь извлекать ответ из внешнего источника. А значит, скажи: можем ли мы в
// runtime добавить функцию в проект?»
//
// 🔒 ОТВЕТ, ПРИНЯТЫЙ ВЛАДЕЛЬЦЕМ: функция как КОД в рантайме невозможна и не
// нужна; функция как ОПИСАНИЕ вызова возможна и работает немедленно. Проект
// собирается `next build`, и файла, которого не было при сборке, в графе модулей
// нет — написать функцию на диск и позвать её можно только после пересборки, то
// есть только через агента. Ровно то ограничение, от которого уходит реестр.
//
// 🛑 `eval` И `new Function` ЗАПРЕЩЕНЫ НАВСЕГДА, И ЭТО НЕ ОСТОРОЖНОСТЬ. Текст,
// пришедший от модели и исполняемый на сервере с ключами и доступом к базе, — не
// гибкость, а открытая дверь: один неудачно описанный признак становится способом
// выполнить что угодно на машине владельца. Поэтому здесь ОПИСАНИЕ, а исполняет
// его код, собранный заранее и умеющий конечное число операций.

/**
 * Что делает функция. Список закрыт, и расширяет его агент, а не описание.
 *
 * 🔒 ЗАКРЫТЫЙ СПИСОК — ЭТО И ЕСТЬ ГРАНИЦА БЕЗОПАСНОСТИ. Открой я «выполни
 * произвольный запрос», описание снова стало бы кодом, и запрет выше потерял бы
 * смысл. Нужна операция, которой нет, — её пишет агент, и это обычная работа.
 */
//   http  — сходить по адресу и взять поле ответа: погода, курс, справочник.
//   model — спросить нашу модель заданным промптом.
//   rag   — спросить граф знаний.
export type FactFnKind = (typeof FACT_FN_KINDS)[number]

/** Когда звать. Пока признаётся только разбор сообщения. */
export type FactFnWhen = "ingest"

/** Что делать, когда источник промолчал. */
export type FactFnOnFail =
  /** Оставить пусто и записать отказ. Разбор продолжается. */
  | "silent"
  /** То же плюс пометка человеку в ответе. */
  | "note"

export type FactFn = {
  kind: FactFnKind
  when: FactFnWhen
  onFail: FactFnOnFail
  /**
   * Адрес для `http`.
   *
   * 🔒 ПРОВЕРЯЕТСЯ БЕЛЫМ СПИСКОМ ХОСТОВ. Свободно описанный адрес — способ
   * заставить наш сервер стучаться куда угодно, включая внутреннюю сеть: там
   * живут слой данных без внешнего замка, граф знаний и метаданные машины.
   * Разрешённые хосты объявляются, остальное отклоняется с названной причиной.
   */
  url?: string
  /**
   * Что подставить в адрес: `{lat}`, `{lon}`, `{date}`, `{text}`.
   *
   * 🔒 ПОДСТАНОВКА ИМЕНОВАННАЯ, А НЕ ПРОИЗВОЛЬНАЯ. Позволь я любое выражение —
   * это снова исполнение чужого текста, только записанное иначе.
   */
  params?: Record<string, string>
  /** Путь к полю ответа: `current.temperature_2m`. */
  pick?: string
  /** Промпт для `kind: "model"` и вопрос для `kind: "rag"`. */
  prompt?: string
  /**
   * Потолок цены одного вызова для `kind: "web"`, в запросах к внешней службе.
   *
   * 🔒 БЮДЖЕТ ОБЪЯВЛЯЕТСЯ В ОПИСАНИИ, А НЕ СПРАШИВАЕТСЯ В МОМЕНТ ВЫЗОВА. Признак
   * срабатывает на входящем сообщении, когда спросить некого: человек не сидит и
   * не ждёт. Незаявленный потолок означает «сколько получится», а счёт за это
   * приходит один раз и целиком.
   */
  budget?: number
}

/** Чем кончился вызов. Отказ — законный исход, а не поломка. */
export type FactFnResult =
  | { ok: true; value: string }
  | { ok: false; reason: FactFnFailure }

export type FactFnFailure =
  /** Адреса нет в белом списке. */
  | "host-not-allowed"
  /** Описание неполно: нет адреса, промпта или пути к полю. */
  | "bad-fn"
  /** Источник не ответил или ответил не тем. */
  | "source-silent"
  /** Поле, названное в `pick`, в ответе отсутствует. */
  | "no-field"
  /** Ключа модели нет. */
  | "no-key"
  /** Род объявлен, исполнитель появится позже. Сегодня это `web` (шаг 87). */
  | "not-implemented"

/**
 * Список родов — первичен, тип выведен из него.
 *
 * 🔒 ДВЕРЬ ОБЯЗАНА ПРОВЕРИТЬ РОД, ПРИШЕДШИЙ СНАРУЖИ, а тип в рантайме не
 * существует. Тот же приём, что у уровней признака: объяви я их порознь —
 * разошлись бы молча, и дверь пропустила бы род, которого исполнитель не знает.
 */
//   web   — СЕДЬМАЯ НАСТРОЙКА ВТОРОГО СЛОЯ (83-1): внешний веб-источник.
//
// 🛑 РОД ОБЪЯВЛЕН, ИСПОЛНИТЕЛЯ У НЕГО ПОКА НЕТ, И ЭТО СКАЗАНО СЛОВАМИ, А НЕ
// ОСТАВЛЕНО МОЛЧАНИЕМ. Сценарий владельца — «вот ссылка, сделай саммари с
// фокусом… придётся использовать внешний браузер такой как exa.ai». Ключ, бюджет
// и живой вызов приезжают шагом 87; до тех пор исполнитель отвечает НАЗВАННЫМ
// отказом `not-implemented`. Молчаливый отказ здесь читался бы как поломка
// источника, и его пошли бы искать снаружи.
export const FACT_FN_KINDS = ["http", "model", "rag", "web"] as const
