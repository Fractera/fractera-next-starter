// РЕЕСТР ПРИЗНАКОВ — договор о том, что система умеет вынимать из сообщения (81-1).
//
// 🔒 ОПРЕДЕЛЕНИЕ, ДАННОЕ ВЛАДЕЛЬЦЕМ 2026-09-01, И ОНО СФОРМУЛИРОВАНО ЧЕРЕЗ
// ОТРИЦАНИЕ — так точнее: «если какие-то из этих признаков не описаны в реестре,
// то значит пользователь не передал инструкцию о том, как декомпозировать такую
// логику, и значит она не попадёт ни в какие соответствующие таблицы и
// сохранится максимум как обычная информация».
//
// Отсюда прямое определение: **признак — объявленная способность узнать в
// сообщении определённый класс фактов, сохранить их отдельно от текста и связать
// с остальным.** Реестр — не список ярлыков, а НАБОР ИНСТРУКЦИЙ ДЕКОМПОЗИЦИИ.
//
// 🔒 ПЯТЬ ЧАСТЕЙ ОБЯЗАТЕЛЬНЫ, И ЭТО ДЕРЖИТ ТИП, А НЕ ДИСЦИПЛИНА. Запись без
// инструкции узнавания бесполезна: система не будет знать, по каким словам искать.
// Запись без поведения при неудаче хуже — она молча теряет половину случаев, и
// именно там живёт пример владельца про «здесь» и про телефон, которого в
// сообщении нет.

/**
 * На каком уровне живёт признак.
 *
 * 🔒 УРОВЕНЬ — НЕ УКРАШЕНИЕ, А ОТВЕТ НА ВОПРОС «КОГДА ЭТО ИЗВЕСТНО». Род входа
 * известен до всякого разбора; намерение — после первого вызова модели; поле —
 * после второго. Смешать их в один список значит обещать, что температура воздуха
 * узнаётся так же, как «это голосовое», а это разные механизмы.
 */
// 🔒 СПИСОК ПЕРВИЧЕН, ТИП ВЫВОДИТСЯ ИЗ НЕГО. Дверь обязана проверить пришедшее
// снаружи значение, а тип в рантайме не существует вовсе. Объяви я тип отдельно
// от списка — они разошлись бы молча, и дверь пропустила бы уровень, которого нет.
//
//   material    — чем сообщение ПРИШЛО: текст, голос. Известно до разбора.
//   intent      — зачем пришло. Первый вызов модели.
//   entity      — чем оказалось: заметка, задача, чек, место, идея. Второй вызов.
//   destination — куда уехало: медиатека, вектор, граф знаний.
//   field       — что извлекли ИЗ содержимого: сумма, дата, координаты, связь.
export const FACT_LEVELS = ["material", "intent", "entity", "destination", "field"] as const
export type FactLevel = (typeof FACT_LEVELS)[number]

/** Форма значения. Решает, как признак хранится и как его показывать. */
//   flag · text · number · money · date · geo · link · list
//   `link` — ссылка на другое сообщение: связь, о которой владелец сказал
//   «всегда и у всех по умолчанию».
export const FACT_VALUE_TYPES = ["flag", "text", "number", "money", "date", "geo", "link", "list"] as const
export type FactValueType = (typeof FACT_VALUE_TYPES)[number]

/**
 * Что делать, когда признак в сообщении подразумевается, но не извлекается.
 *
 * 🔒 ЭТО ЧАСТЬ ЗАПИСИ, А НЕ ОШИБКА ИЗВЛЕЧЕНИЯ. Пример владельца: «здесь
 * продаются пирожки» — место названо, координат нет; «телефон может прийти из
 * другого сообщения или прямого вопроса». Не объявив поведение заранее, система
 * молча теряет половину случаев и выглядит глупой ровно там, где она права.
 */
//   silent — промолчать: признак необязателен.
//   ask    — задать уточняющий вопрос человеку.
//   join   — поискать в соседних сообщениях и склеить.
export const FACT_ON_MISSING = ["silent", "ask", "join"] as const
export type FactOnMissing = (typeof FACT_ON_MISSING)[number]

/** Одна запись реестра. Пять частей — плюс происхождение и состояние. */
export type Fact = {
  /** Машинное имя, по нему хранятся значения. Не меняется никогда. */
  key: string
  level: FactLevel
  /** Имя человеческими словами. */
  title: string
  /** Что это, словами человека: зачем он и что попадает внутрь. */
  description: string
  valueType: FactValueType
  /**
   * Инструкция узнавания — по каким словам и в каком виде это встречается.
   *
   * 🔒 ИМЕННО ЭТО ЕДЕТ В МОДЕЛЬ И ИМЕННО ЭТОГО СЕГОДНЯ НЕТ. Без неё признак —
   * колонка, которую никто не заполняет.
   */
  howToFind: string
  /** Где значение живёт: колонка сообщения, склад значений, чужая служба. */
  storedIn: string
  onMissing: FactOnMissing
  /**
   * Встроенный — тот, что уже работает в коде и порождён из своего источника.
   *
   * 🔒 ВСТРОЕННЫЙ НЕЛЬЗЯ ВЫКЛЮЧИТЬ И НЕЛЬЗЯ ПРАВИТЬ. Он описывает то, что система
   * делает по устройству; правка описания рядом с неизменным поведением — это
   * вторая правда, которая разойдётся с первой на первом же изменении кода.
   */
  /**
   * Описание внешнего вызова, строкой JSON. Пусто — признак берётся из
   * самого сообщения (81-8).
   *
   * 🛑 ЗДЕСЬ НЕ БЫВАЕТ КОДА, И ЭТО ДЕРЖИТ ФОРМА, А НЕ ДИСЦИПЛИНА: исполнитель
   * умеет конечное число операций и не умеет исполнять текст вовсе.
   */
  fn?: string
  builtin: boolean
  /** Выключенный признак не участвует в разборе. У встроенных всегда `true`. */
  enabled: boolean
  /**
   * Обязательный — выключить нельзя даже владельцу.
   *
   * 🔒 СЕГОДНЯ ТАКОЙ ОДИН: СВЯЗЬ СООБЩЕНИЙ. Слово владельца 2026-09-01: «обрати
   * внимание на первый пункт зависимых сообщений, который должен быть всегда и у
   * всех по умолчанию, как минимум это связанные сообщения».
   */
  required?: boolean
}
