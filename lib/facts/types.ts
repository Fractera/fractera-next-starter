// РЕЕСТР ПРИЗНАКОВ — договор о том, что система умеет вынимать из сообщения (81-1).
//
// 🔒 ОПРЕДЕЛЕНИЕ, ДАННОЕ ВЛАДЕЛЬЦЕМ 2026-09-01, И ОНО СФОРМУЛИРОВАНО ЧЕРЕЗ
// ОТРИЦАНИЕ — так точнее: «если какие-то из этих признаков не описаны в реестре,
// то значит пользователь не передал инструкцию о том, как декомпозировать такую
// логику, и значит она не попадёт ни в какие соответствующие таблицы и
// сохранится максимум как обычная информация».
//
// Отсюда прямое определение: **признак — объявленная способность узнать в
// сообщении определённый класс фактов, сохранить их отдельно от текста и связать
// с остальным.** Реестр — не список ярлыков, а НАБОР ИНСТРУКЦИЙ ДЕКОМПОЗИЦИИ.
//
// 🔒 ПЯТЬ ЧАСТЕЙ ОБЯЗАТЕЛЬНЫ, И ЭТО ДЕРЖИТ ТИП, А НЕ ДИСЦИПЛИНА. Запись без
// инструкции узнавания бесполезна: система не будет знать, по каким словам искать.
// Запись без поведения при неудаче хуже — она молча теряет половину случаев, и
// именно там живёт пример владельца про «здесь» и про телефон, которого в
// сообщении нет.

/**
 * На каком уровне живёт признак.
 *
 * 🔒 УРОВЕНЬ — НЕ УКРАШЕНИЕ, А ОТВЕТ НА ВОПРОС «КОГДА ЭТО ИЗВЕСТНО». Род входа
 * известен до всякого разбора; намерение — после первого вызова модели; поле —
 * после второго. Смешать их в один список значит обещать, что температура воздуха
 * узнаётся так же, как «это голосовое», а это разные механизмы.
 */
// 🔒 СПИСОК ПЕРВИЧЕН, ТИП ВЫВОДИТСЯ ИЗ НЕГО. Дверь обязана проверить пришедшее
// снаружи значение, а тип в рантайме не существует вовсе. Объяви я тип отдельно
// от списка — они разошлись бы молча, и дверь пропустила бы уровень, которого нет.
//
//   material    — чем сообщение ПРИШЛО: текст, голос. Известно до разбора.
//   intent      — зачем пришло. Первый вызов модели.
//   entity      — чем оказалось: заметка, задача, чек, место, идея. Второй вызов.
//   destination — куда уехало: медиатека, вектор, граф знаний.
//   field       — что извлекли ИЗ содержимого: сумма, дата, координаты, связь.
export const FACT_LEVELS = ["material", "intent", "entity", "destination", "field"] as const
export type FactLevel = (typeof FACT_LEVELS)[number]

/** Форма значения. Решает, как признак хранится и как его показывать. */
//   flag · text · number · money · date · geo · link · list
//   `link` — ссылка на другое сообщение: связь, о которой владелец сказал
//   «всегда и у всех по умолчанию».
export const FACT_VALUE_TYPES = ["flag", "text", "number", "money", "date", "geo", "link", "list"] as const
export type FactValueType = (typeof FACT_VALUE_TYPES)[number]

/**
 * Что делать, когда признак в сообщении подразумевается, но не извлекается.
 *
 * 🔒 ЭТО ЧАСТЬ ЗАПИСИ, А НЕ ОШИБКА ИЗВЛЕЧЕНИЯ. Пример владельца: «здесь
 * продаются пирожки» — место названо, координат нет; «телефон может прийти из
 * другого сообщения или прямого вопроса». Не объявив поведение заранее, система
 * молча теряет половину случаев и выглядит глупой ровно там, где она права.
 */
//   silent — промолчать: признак необязателен.
//   ask    — задать уточняющий вопрос человеку.
//   join   — поискать в соседних сообщениях и склеить.
export const FACT_ON_MISSING = ["silent", "ask", "join"] as const
export type FactOnMissing = (typeof FACT_ON_MISSING)[number]

// ─────────────────────────────────────────────────────────────────────────────
// ВТОРОЙ СЛОЙ РЕЕСТРА — ВОСЕМЬ НАСТРОЕК (83-1).
//
// 🔒 ЗАЧЕМ ОН ПОНАДОБИЛСЯ. Первый слой отвечает на вопрос «что вынуть из
// сообщения». Владелец принёс шесть сценариев — калории, команда, идеи, статья,
// тренды, видео — и ни один из них на первом слое не выражается. Разбор упёрся в
// три стены, и каждая из них есть отсутствующая НАСТРОЙКА, а не отсутствующий код:
//
//   признак даёт ОДНО значение       → калориям нужны ккал, белки, жиры, углеводы
//   факт неизменен и ничей           → задание Мишино, и оно меняет состояние
//   накопленное нечем спросить       → «сколько я за месяц всего съел калорий»
//
// 🔒 ВОСЕМЬ НАСТРОЕК, И ЧИСЛО ПРАВИТСЯ ВМЕСТЕ С ПЕРЕЧИСЛЕНИЕМ — иначе оно
// разойдётся с кодом молча, и это класс ошибки, оплаченный в проекте ЧЕТЫРЕЖДЫ за
// три дня («пять» → «шесть» → «семь» → «восемь» инструментов):
//
//   1 produces   2 derivedFrom   3 aggregate   4 subject
//   5 lifecycle  6 schedules     7 fn.kind="web" (в `fn-types.ts`)   8 model
//
// `unit` и `derivedSlot` девятой и десятой настройками НЕ считаются: первая —
// принадлежность накопления, вторая — принадлежность производности. Своего
// смысла в отрыве от хозяина у них нет.
//
// 🔒 ВСЕ ВОСЕМЬ НЕОБЯЗАТЕЛЬНЫ, И ЭТО НЕ МЯГКОСТЬ. 25 признаков реестра 81 уже
// лежат в базе без них и обязаны читаться дальше без единой правки; настройка,
// объявленная обязательной, сделала бы каждую существующую запись негодной.

/**
 * Как значение НАКАПЛИВАЕТСЯ по окну времени.
 *
 * 🔒 БЕЗ ЭТОГО ОБЪЯВЛЕНИЯ ВОПРОС «СКОЛЬКО ЗА НЕДЕЛЮ» НЕ ИМЕЕТ ОТВЕТА, И ЭТО НЕ
 * недоработка интерфейса. Складывать калории законно, складывать температуру
 * воздуха — бессмыслица, а складывать статусы — ошибка. Знает разницу только тот,
 * кто признак завёл; догадка кода здесь выглядела бы как работающая функция и
 * врала бы числами.
 */
//   none  — не накапливается: спрашивать бессмысленно.
//   sum   — сложить: калории, расходы, километры.
//   avg   — среднее: вес, температура, оценка.
//   count — сколько раз встретилось: тренировки, отказы.
//   last  — последнее известное: текущий вес, текущий статус.
export const FACT_AGGREGATE = ["none", "sum", "avg", "count", "last"] as const
export type FactAggregate = (typeof FACT_AGGREGATE)[number]

/**
 * К КОМУ относится факт.
 *
 * 🔒 СЦЕНАРИЙ ВЛАДЕЛЬЦА, КОТОРЫЙ ЭТО ОТКРЫВАЕТ: «Мише дали задание сделать
 * то-то… Миша молодец Петя не молодец». Факт принадлежит не сообщению, а
 * человеку, и без хозяина вопрос «как дела у Миши» не формулируется вовсе.
 */
//   none   — факт ничей: погода, курс, время.
//   self   — факт о самом владельце: что он съел, сколько потратил.
//   person — факт о названном человеке; хозяин опознаётся при разборе.
export const FACT_SUBJECT = ["none", "self", "person"] as const
export type FactSubject = (typeof FACT_SUBJECT)[number]

/**
 * Порождает ли признак ОТЛОЖЕННОЕ действие.
 *
 * 🛑 ОБЪЯВЛЕНИЕ ЕСТЬ, ИСПОЛНЕНИЯ ПОКА НЕТ — и это сказано здесь, а не
 * подразумевается. Календарь сегодня пуст (0 строк, напоминания не доезжают);
 * признак, кладущий напоминание поверх мёртвого календаря, честно вернёт ноль и
 * будет выглядеть сломанным. Починка — шаг 90, исполнение — шаг 86.
 */
//   none     — ничего не откладывает.
//   reminder — «напомни мне об этом в воскресенье».
//   check    — «проверить работу по таймеру».
export const FACT_SCHEDULES = ["none", "reminder", "check"] as const
export type FactSchedules = (typeof FACT_SCHEDULES)[number]

/**
 * Какой моделью признак извлекается.
 *
 * 🔒 ДОРОГАЯ МОДЕЛЬ ОБЪЯВЛЯЕТСЯ ЗАРАНЕЕ, А НЕ ВЫБИРАЕТСЯ В МОМЕНТ ВЫЗОВА. Слово
 * владельца о сценарии трендов: «Соглашаемся с тем что это дорогой кейс по
 * Token». Согласие на ИЗВЕСТНУЮ цену — это то, что можно дать заранее; согласие
 * на любую цену никто не давал, и сюрприз в счёте нельзя отменить задним числом.
 */
export const FACT_MODEL = ["cheap", "strong"] as const
export type FactModel = (typeof FACT_MODEL)[number]

/**
 * Одно из НЕСКОЛЬКИХ значений признака.
 *
 * 🔒 ЭТО НЕ «НЕСКОЛЬКО ПРИЗНАКОВ», И РАЗНИЦА СОДЕРЖАТЕЛЬНАЯ. Из «трёх пирожков
 * по 25» нужны ккал, белки, жиры и углеводы — четыре числа ОДНОГО факта еды.
 * Заведи мы четыре признака, они извлекались бы четырьмя независимыми разборами
 * одного и того же куска текста и разошлись бы на первом же несовпадении.
 *
 * 🔒 `slot` ПРОХОДИТ ТУ ЖЕ СТРОГУЮ СБОРКУ, ЧТО ИМЯ ТАБЛИЦЫ. Он приезжает из
 * свободных слов человека через модель и попадает в значение колонки.
 */
export type FactProduces = {
  slot: string
  title: string
  valueType: FactValueType
  /** Единица: «ккал», «г», «км». Пусто — величина безразмерна. */
  unit?: string
}

/**
 * Жизненный цикл признака-СУЩНОСТИ.
 *
 * 🔒 ВТОРОЕ ИСКЛЮЧЕНИЕ ПО ПРИРОДЕ, И ОНО НАЗЫВАЕТСЯ ВСЛУХ. Первым была связь
 * сообщений — отношение между двумя, а не факт об одном (81-2). Здесь — факт, у
 * которого есть время жизни: задание выдано, потом проверено, потом оценено.
 *
 * 🔒 ЕДИНЫЙ СТАНДАРТ ХРАНЕНИЯ ПРИ ЭТОМ НЕ НАРУШАЕТСЯ: форма таблицы остаётся
 * одна на все признаки, переход пишется НОВОЙ СТРОКОЙ, а «текущее» читается как
 * последняя по времени. Особой таблицы под задачи не появляется — иначе вернулся
 * бы ровно тот выбор без критерия, против которого стоит решение владельца.
 */
export type FactLifecycle = {
  statuses: string[]
  initial: string
}

/** Одна запись реестра. Пять частей — плюс происхождение и состояние. */
export type Fact = {
  /** Машинное имя, по нему хранятся значения. Не меняется никогда. */
  key: string
  level: FactLevel
  /** Имя человеческими словами. */
  title: string
  /** Что это, словами человека: зачем он и что попадает внутрь. */
  description: string
  valueType: FactValueType
  /**
   * Инструкция узнавания — по каким словам и в каком виде это встречается.
   *
   * 🔒 ИМЕННО ЭТО ЕДЕТ В МОДЕЛЬ И ИМЕННО ЭТОГО СЕГОДНЯ НЕТ. Без неё признак —
   * колонка, которую никто не заполняет.
   */
  howToFind: string
  /** Где значение живёт: колонка сообщения, склад значений, чужая служба. */
  storedIn: string
  onMissing: FactOnMissing
  /**
   * Встроенный — тот, что уже работает в коде и порождён из своего источника.
   *
   * 🔒 ВСТРОЕННЫЙ НЕЛЬЗЯ ВЫКЛЮЧИТЬ И НЕЛЬЗЯ ПРАВИТЬ. Он описывает то, что система
   * делает по устройству; правка описания рядом с неизменным поведением — это
   * вторая правда, которая разойдётся с первой на первом же изменении кода.
   */
  /**
   * Описание внешнего вызова, строкой JSON. Пусто — признак берётся из
   * самого сообщения (81-8).
   *
   * 🛑 ЗДЕСЬ НЕ БЫВАЕТ КОДА, И ЭТО ДЕРЖИТ ФОРМА, А НЕ ДИСЦИПЛИНА: исполнитель
   * умеет конечное число операций и не умеет исполнять текст вовсе.
   */
  fn?: string
  builtin: boolean
  /** Выключенный признак не участвует в разборе. У встроенных всегда `true`. */
  enabled: boolean

  // ── РАСКРЫТИЕ КАРТОЧКИ: РУКОПИСНАЯ ПОЛОВИНА (81-9)
  //
  // 🔒 ДВЕ СТРОКИ ИЗ ПЯТИ НЕВЫВОДИМЫ ИЗ КОДА, И ЭТО НАЗВАНО, А НЕ ОБНАРУЖЕНО
  // ПОТОМ. Остальные три раскрытия порождаются (`lib/facts/detail.ts`): что
  // извлекается — из типа, чем добыто — из `fn`, связанные функции — из модуля
  // происхождения. А «как человек это ГОВОРИТ» и «что при этом ТЕРЯЕТСЯ» в коде
  // не записано нигде: первое — знание о людях, второе — суждение о разрыве
  // между извлечением и хранением.
  //
  // 🔒 ЛЕЖАТ ЗДЕСЬ, РЯДОМ С МЕХАНИЗМОМ, А НЕ В СЛОВАРЕ ЭКРАНА. Текст, оторванный
  // от кода, устаревает молча; в этом файле правящий механизм видит его в том же
  // месте. Смягчение, а не лечение: разойтись они всё равно могут.
  //
  // 🔒 ПУСТОЕ ОСТАЁТСЯ ПУСТЫМ. Признак без примера показывает «пример не описан»,
  // а не выдуманную фразу: придуманный пример — правдоподобная ложь о том, что
  // система понимает, а весь смысл раскрытия ровно в обратном.

  /** Как человек это говорит. Одна настоящая фраза, а не формулировка задачи. */
  example?: string
  /**
   * Что признак вынимает и НЕ сохраняет.
   *
   * 🛑 САМАЯ ЦЕННАЯ СТРОКА РАСКРЫТИЯ, И ЕЁ ВЛАДЕЛЕЦ НЕ ЗАКАЗЫВАЛ. Четыре
   * заказанные строки рассказывают, что признак умеет, и молчат о том, что он
   * умеет и выбрасывает. Пример измерен: `intent.capture` при каждом разборе
   * получает от модели два-шесть тегов `facets` — и они не сохраняются никуда.
   */
  lost?: string

  // ── ВТОРОЙ СЛОЙ (83-1). Все восемь необязательны; отсутствие = прежнее поведение.

  /** 1. Несколько именованных значений вместо одного. Пусто — одно значение. */
  produces?: FactProduces[]
  /** 2. Ключ признака-источника: значение считается ИЗ него, а не ищется в тексте. */
  derivedFrom?: string
  /** Какой слот источника брать, если тот даёт несколько значений. */
  derivedSlot?: string
  /** 3. Как накапливается по окну времени. Умолчание — не накапливается. */
  aggregate?: FactAggregate
  /** Единица накопления: «ккал», «₽», «км». Осмысленна только при `aggregate`. */
  unit?: string
  /** 4. К кому относится факт. Умолчание — ничей. */
  subject?: FactSubject
  /** 5. Состояния сущности. Пусто — обычный неизменный факт. */
  lifecycle?: FactLifecycle
  /** 6. Порождает ли отложенное действие. Умолчание — нет. */
  schedules?: FactSchedules
  /** 8. Какой моделью извлекать. Умолчание — дешёвой. (7 — `fn.kind`, см. `fn-types.ts`.) */
  model?: FactModel
  /**
   * Обязательный — выключить нельзя даже владельцу.
   *
   * 🔒 СЕГОДНЯ ТАКОЙ ОДИН: СВЯЗЬ СООБЩЕНИЙ. Слово владельца 2026-09-01: «обрати
   * внимание на первый пункт зависимых сообщений, который должен быть всегда и у
   * всех по умолчанию, как минимум это связанные сообщения».
   */
  required?: boolean
}
