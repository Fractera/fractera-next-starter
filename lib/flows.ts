// ЦВЕТ ПОТОКА — один на слой прав, один на весь продукт.
//
// 🔒 ЖИВЁТ ЗДЕСЬ, А НЕ В ПОЛОСЕ И НЕ В ЯЩИКЕ. Цвет показывают ДВА места сразу:
// вертикальная лента на странице и точка в ящике аккаунта. Две копии таблицы
// разошлись бы на первой же правке, и разошлись бы молча — человек увидел бы
// синюю ленту при зелёной точке и перестал бы верить обеим.
//
// 🔒 ПОЧЕМУ ЦВЕТА АБСОЛЮТНЫЕ, А НЕ ТОКЕНЫ ТЕМЫ. Это единственное законное
// исключение из правила «цвет берётся из темы» (CONTENT-ENGINE.md §13): здесь
// цвет НЕСЁТ СМЫСЛ — он и есть имя потока, произнесённое без слов. Токен темы
// меняется вместе с темой, а значение «финансы» меняться не должно. Оттенки
// выбраны так, чтобы белый текст читался на них в обеих темах.
//
// Порядок тот же, что у `PROTECTED_GROUP_ROLES`: своё → чужое по долгу службы →
// деньги → сам проект.
