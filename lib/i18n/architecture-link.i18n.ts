import words from "./architecture-link.i18n.json"

// Подписи двух ссылок, ведущих на страницу архитектуры: кнопка в подвале и
// кнопка на главной.
//
// 🔒 ПОЧЕМУ ПОДПИСИ ЗДЕСЬ, А НЕ В ЯЗЫКОВЫХ ЯЧЕЙКАХ СТРАНИЦЫ. Кнопка на главной
// стоит внутри секции `noBill`, чьи слова живут в десяти ячейках. Положи подпись
// туда — и добавление кнопки стало бы правкой десяти файлов с текстом, то есть
// переводом; а это не перевод, это одна и та же подпись одного и того же
// платформенного элемента. В ячейках остаётся МАШИННОЕ поле «здесь стоит кнопка
// на страницу архитектуры», слова — тут.
//
// 🔒 ЯЗЫК ОДИН, И ЭТО ОСОЗНАННОЕ СОСТОЯНИЕ (владелец, 2026-08-17). Владелец
// переводит корпуса внешней моделью и просил не тратить на это токены агента.
// Структура заведена в форме, пригодной для обмена (тип здесь, слова в JSON
// рядом), и зарегистрирована в `DICTS` (`scripts/i18n-export.mjs`):
//
//   npm run i18n:export architecture-link --langs es,fr,de,it,pt,pl,tr,nl
//   npm run i18n:import architecture-link <ответ модели>
//
// До прихода перевода словарь НЕ вносится в `scripts/check-i18n.mjs`: список
// сторожа объявляет, сколько языков файл ОБЯЗАН нести, и записать туда «один»
// значило бы узаконить недоделку. Пока перевода нет, кнопки на всех языках
// подписаны по-английски — резолвер откатывается на `en`.

export type ArchitectureLinkUi = {
  /** Кнопка в подвале, рядом с настройками cookie и панелью. */
  footer: string
  /** Кнопка на главной, под выводом раздела «вы никому не платите». */
  homeCta: string
}

const UI = words as Record<string, ArchitectureLinkUi>

export function architectureLinkUi(lang: string): ArchitectureLinkUi {
  return UI[lang] ?? UI[lang.slice(0, 2)] ?? UI.en
}
