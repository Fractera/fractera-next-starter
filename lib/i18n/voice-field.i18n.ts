import words from "./voice-field.i18n.json"

// СЛОВА ГОЛОСОВОГО ВВОДА — резолвер над JSON-словарём (шаг 32-4, 2026-08-28).
//
// 🔒 СЛОВАРЬ ПЕРЕЕХАЛ ИЗ `.ts` В JSON, И ЭТО НЕ ВКУСОВЩИНА. Механизм обмена
// переводами (`npm run i18n:export` / `i18n:import`) читает и пишет ФАЙЛ; словарь,
// разложенный по объектам в коде, он не видит вовсе. Пока слова лежали в
// TypeScript, владелец не мог ни выгрузить массив для внешней модели, ни внести
// её ответ — то есть не мог масштабировать переводы без меня. Он просил ровно
// обратного: «просто сообщи, где я могу открыть и получить пример реализации с
// двумя языками, чтобы самостоятельно масштабировать его без твоего участия».
//
//   npm run i18n:export voice-field --langs <языки>
//   npm run i18n:import voice-field <ответ модели>
//
// 🔒 ДЕСЯТЬ ЯЗЫКОВ ПОЛНЫЕ ТОЛЬКО У ДВУХ. `en` и `ru` несут все 18 строк, включая
// четыре новые (кнопка микрофона и слова контейнера); остальные восемь достались
// в наследство от прежнего словаря и пока без новых строк — резолвер откатится на
// английский. Дописывать их самому запрещено: переводы приходят от внешней модели
// владельца, и сочинённый агентом перевод дороже отсутствующего — его никто не
// перепроверит.
//
// 🔒 В `check:i18n` СЛОВАРЬ НЕ ВНОСИТСЯ, ПОКА ПЕРЕВОДЫ НЕ ПРИДУТ. Список сторожа
// объявляет, сколько языков файл ОБЯЗАН нести; записать туда «два» значило бы
// узаконить недоделку, а «82» — уронить сборку на честном промежуточном
// состоянии.
//
// 🔒 СЛОВА ОБРАЗЦА НА СТРАНИЦЕ КАТАЛОГА ЛЕЖАТ ЗДЕСЬ ЖЕ, И ЭТО НЕ СМЕШЕНИЕ (32-6).
// Образец существует ради одной вещи: показать владельцу **пример реализации на
// двух языках**, который он масштабирует сам. Разложи его слова по двум файлам —
// и пример перестанет быть примером: одна команда обмена выгрузит половину, а
// вторая половина останется необъяснённой. Один словарь, два языка, одна пара
// команд — ровно то, что он просил.

export type VoiceStrings = {
  /** Подпись кнопки в маленьком облике: «удерживайте, чтобы говорить». */
  hold: string
  /** Подпись кнопки микрофона в контейнере — для читалок экрана. */
  mic: string
  recording: string
  transcribing: string
  /** Подсказка кнопки, когда микрофон доступен. */
  tipOk: string
  /** Отказ: соединение не защищено (нужен HTTPS или localhost). */
  tipInsecure: string
  /** Отказ: браузер не дал разрешения на микрофон. */
  micDenied: string
  /** Отказ: микрофона в системе нет. */
  micNoDevice: string
  /** Отказ: страница внутри фрейма, браузер микрофон не отдаёт. */
  frame: string
  failed: string
  nothing: string
  /** Отказ: не подключён ключ OpenAI. */
  noKey: string
  draftTitle: string
  accept: string
  discard: string
  /** Слова образца на странице каталога — живут ЗДЕСЬ намеренно, см. шапку. */
  specimenTitle: string
  specimenNote: string
  specimenFieldCaption: string
  specimenAreaCaption: string
  specimenI18nTitle: string
  specimenI18nNote: string
  /** Слова контейнера `VoiceField`. */
  fieldTitle: string
  fieldHint: string
  fieldComment: string
}

const UI = words as Record<string, Partial<VoiceStrings>>

/**
 * Слова на языке страницы, с откатом на английский — по ключу, а не по языку.
 *
 * 🔒 ОТКАТ ПОКЛЮЧЕВОЙ, И ЭТО ВАЖНО ИМЕННО СЕЙЧАС. Восемь языков несут старые
 * строки и не несут четырёх новых. Откат «весь язык или ничего» стёр бы
 * испанскому его собственные, уже переведённые слова ради четырёх отсутствующих;
 * поключевой отдаёт переведённое переведённым, а недостающее — по-английски.
 */
export function voiceStrings(lang: string): VoiceStrings {
  const en = UI.en as VoiceStrings
  const own = UI[lang] ?? UI[lang.slice(0, 2)] ?? {}
  return { ...en, ...own }
}
