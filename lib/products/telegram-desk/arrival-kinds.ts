export const ARRIVAL_KINDS = [
  "text",
  "voice",
  "photo",
  "video",
  "document",
  "location",
  "contact",
  "link",
  "calendar-date",
] as const

export type ArrivalKind = (typeof ARRIVAL_KINDS)[number]

/** То, что канал сообщает о сообщении. Без базы и без продукта — чистые данные. */
export type Arrival = {
  /** Чем сообщение было в канале до расшифровки: `text` или `voice`. */
  kind?: string
  /** Род вложения от службы каналов: `image` · `video` · `document` · `audio`. */
  objectType?: string
  text?: string
  lat?: number | null
  lon?: number | null
  /** Присланная карточка контакта. 🛑 Служба сегодня её НЕ шлёт — см. ниже. */
  contact?: unknown
}

/**
 * Ссылка узнаётся по тому, что сообщение ЕСТЬ ссылка, а не содержит её.
 *
 * 🔒 СТРОГО, И ЭТО НАМЕРЕННО. «Посмотри http://…, там про пирожки» — рассказ со
 * ссылкой внутри, и род у него текстовый: иначе половина обычных сообщений
 * перестала бы быть текстом. Разметку сущностей Telegram служба нам не передаёт —
 * измерено чтением `services/channels/server.js`, — так что решает форма текста.
 */
function isLink(text: string): boolean {
  const t = text.trim()
  return /^https?:\/\/\S+$/i.test(t)
}

/**
 * Род пришедшего.
 *
 * 🔒 ПОРЯДОК ПРОВЕРОК СОДЕРЖАТЕЛЕН, А НЕ СЛУЧАЕН. Голос идёт первым: расшифровка
 * делает его неотличимым от текста дальше по потоку, и единственное место, где
 * это ещё видно, — здесь. Фотография с подписью — фотография, а не текст: смысл
 * на снимке, подпись рядом с ним (закон, оплаченный 2026-08-23 выброшенным чеком).
 *
 * 🛑 `contact` И `calendar-date` СЕГОДНЯ НЕ ВОЗВРАЩАЮТСЯ НИКОГДА, и это измерено,
 * а не предположено: служба каналов не читает `msg.contact` вовсе — сообщение без
 * текста и без файла она отбрасывает целиком (`if (!text && !fileId) continue`), —
 * а канала с формой календаря пока не существует. Рода объявлены, потому что
 * владелец их назвал; **их пустота названа словами в реестре**, а не спрятана.
 */
export function arrivalKindOf(a: Arrival): ArrivalKind {
  if (a.contact) return "contact"
  if (a.kind === "voice") return "voice"
  if (a.objectType === "audio") return "voice"
  if (a.objectType === "image") return "photo"
  if (a.objectType === "video") return "video"
  if (a.objectType === "document") return "document"
  if (a.lat != null && a.lon != null) return "location"
  if (isLink(String(a.text ?? ""))) return "link"
  return "text"
}
