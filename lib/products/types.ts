// ПРОДУКТОВАЯ СУЩНОСТЬ — одна на весь проект.
//
// 🔒 ЖИВЁТ В `lib/`, А НЕ В ПАПКЕ КАКОЙ-ТО ОДНОЙ СТРАНИЦЫ. Товар нужен публичной
// витрине, странице менеджера, странице цен бухгалтера и маршрутам `/api/*` —
// значит общий предок этих потребителей корень проекта, и никакой не
// `(protectedLayer)`. Сначала тип лежал внутри `(staff)`, и витрина покупателя
// импортировала его ИЗ ГРУППЫ ПРАВ ПЕРСОНАЛА: одна группа незаметно стала
// складом для всех, а следующая (finance) закрепила бы это навсегда.
//
// Правило, которое из этого выведено: группа НИКОГДА не тянет из соседней
// группы. Нужное двум группам поднимается в `(protectedLayer)/_*`, нужное ещё и
// публичному слою — сюда.

export type Product = {
  id: string
  name: string
  price: number
  /** Базовый (английский) текст. Переводы — в `i18n`. */
  description: string | null
  /**
   * Переводы полей одной строкой JSON: `{ "name": { "ru": "…" } }`.
   * Разрешается через `lib/products/localize.ts`; колонка на язык не заводится —
   * каждый новый язык требовал бы миграции схемы.
   */
  i18n: string | null
  media_id: string | null
  media_url: string | null
  /** Размеры и размытая подложка картинки — из записи хранилища, скопированы сюда
   *  при её прикреплении. Читаются вместе со строкой: страница каталога иначе
   *  делала бы по обращению к хранилищу на каждый товар. */
  media_width?: number | null
  media_height?: number | null
  media_blur?: string | null
  created_at: string
}
