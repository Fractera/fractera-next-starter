//
// 🔒 ЕГО ПРАВИЛО ДОСЛОВНО: «для каждого действия мы создаём свой инструмент,
// который владеет навыком и умеет делать только одно действие». Отсюда этот
// лист: у каждого шага разбора есть ИМЯ инструмента и описание того, что он
// умеет, — и колонка «Инструмент» показывает имя, а описание отдаёт подсказкой
// под курсором.
//
// 🔒 «МОДЕЛЬ» — НЕ ИМЯ ИНСТРУМЕНТА. Модель это то, ЧЕМ инструмент внутри себя
// пользуется, как база или сеть; называть её в колонке — всё равно что писать
// «электричество» вместо имени прибора. ✗ так было до этой правки.
//
// 🔒 У ИНСТРУМЕНТА СВОЯ ИНСТРУКЦИЯ, И КОЛОНКА «ИНСТРУКЦИЯ» ЭТО ГОВОРИТ СЛОВАМИ.
// Его слова: «у этого инструмента внутри своя инструкция, поэтому здесь вместо
// длинного текста просто пишешь, что использует собственную инструкцию».

export type Actor = {
  /** Имя в колонке «Инструмент». */
  name: string
  /** Что умеет — всплывает подсказкой при наведении. */
  what: string
  /** Текст для колонки «Инструкция», когда инструкция у инструмента своя. */
  ownInstruction: string
}

