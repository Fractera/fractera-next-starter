import { nowMs } from "./store"
import { HERMES, REGISTRY_EVOLUTION } from "./actors"
import type { TaskRow } from "./types"

// ДВА ФЕЙКОВЫХ ИНСТРУМЕНТА — ЗАГЛУШКИ ЗА НАСТОЯЩИМ КОНТРАКТОМ (решение владельца
// 2026-09-02).
//
// 🔒 ЗАГЛУШКА ПРОВЕРЯЕТ ШОВ, А НЕ ИСПОЛНИТЕЛЯ. Его слова: «сейчас мы будем
// вызывать фейковый инструмент, который будет отрабатывать и возвращать ответ
// 200, как будто бы мы его сделали и он существует — это позволит нам в любой
// момент вернуться к его разработке и усилить архитектуру». Цепочка целиком —
// узнали → позвали → получили → записали → показали — работает уже сегодня;
// заменить заглушку потом значит поменять ОДНУ реализацию за контрактом.
//
// 🛑 И РОВНО ПОЭТОМУ ОТВЕТ ПОМЕЧЕН НЕНАСТОЯЩИМ В ДВУХ МЕСТАХ: в тексте строки,
// которую читает человек, и в поле `fake` самой строки, которое поедет в таблицы.
// Непомеченная выдумка складывается с настоящими числами, и разделить их потом
// нечем — это тот же необратимый класс, что слияние субъектов.
//
// 🪦 ЗАГЛУШКА-ОБМАНКА, КОТОРУЮ ПРОЕКТ ЗАПРЕЩАЕТ, — ЭТО ДРУГОЕ. Запрещён узел,
// который ДЕЛАЕТ ВИД, что работает. Здесь работает всё, кроме самого вычисления,
// и вычисление названо ненастоящим вслух.

/** Что вернул фейковый инструмент. Форма — та же, что у будущего настоящего. */
export type FakeCall = {
  /** Имя инструмента, каким оно попадёт в колонку «Инструмент». */
  tool: string
  /** Что инструмент умеет — подсказка под курсором. */
  what: string
  /** Чем спросили — попадёт в колонку «Инструкция». */
  instruction: string
  /** Что ответил — попадёт в колонку «Выход». */
  output: string
  /** Что делать дальше по итогам этого ответа. */
  next: string
  /** HTTP-исход, как у настоящей службы: сегодня всегда 200. */
  status: number
}

const FAKE_MARK = "⚠️ ответ ненастоящий (заглушка)"

/**
 * ФЕЙКОВЫЙ ГЕРМЕС — исполнитель сложных задач.
 *
 * 🔒 ЕГО МЕСТО В СТРАТЕГИИ: второй режим бота. Простое решается реестром,
 * сложное уходит сюда, а итогом работы Гермеса **всегда** становится ТЗ в
 * `pre-steps` — ответ человеку не цель (ответ владельца 2026-09-02).
 *
 * 🛑 СЕГОДНЯ ОН НИЧЕГО НЕ ИССЛЕДУЕТ И НИЧЕГО НЕ ПИШЕТ. Отвечает 200 и говорит,
 * что сделал бы. Настоящий появится отдельным шагом — за этим же контрактом.
 */
export function fakeHermes(request: string): FakeCall {
  return {
    tool: HERMES.name,
    what: HERMES.what,
    instruction: HERMES.ownInstruction,
    output: `${FAKE_MARK}. Задача принята внешним агентом. Он исследовал бы запрос «${request}» доступными ему средствами — навыки, MCP, внешние API, ИИ-браузер — и вернул бы техническое задание в pre-steps.`,
    next: "Создать техническое задание в pre-steps по результату работы агента.",
    status: 200,
  }
}

/**
 * ФЕЙКОВЫЙ ИНСТРУМЕНТ ЭВОЛЮЦИИ РЕЕСТРА — облако смыслов и счётчики.
 *
 * 🔒 ЗАЧЕМ ОН НУЖЕН, СЛОВАМИ ВЛАДЕЛЬЦА: «пользователь без конца почти в каждом
 * сообщении говорит об овощах. В реестр смыслов попадает слово „овощи“, при
 * каждом добавлении счётчик растёт; при достижении, например, 50 запускаем
 * анализ связанных сообщений моделью и получаем НОВЫЙ элемент реестра признаков
 * с правилами и атрибутами».
 *
 * 🔒 ЭТО ВТОРОЕ ПРАВИЛО, КОТОРОЕ ИСПОЛНЯЕТСЯ ВСЕГДА — рядом с поиском связи с
 * другим сообщением. Оба идут на каждом разборе, независимо от того, что нашлось
 * в реестре: реестр отвечает «что я умею», а это — «чему пора научиться».
 *
 * 🛑 СЕГОДНЯ СМЫСЛЫ НЕ ИЗВЛЕКАЮТСЯ И СЧЁТЧИКИ НЕ РАСТУТ. Отвечает 200.
 */
export function fakeMeaningRegistry(request: string): FakeCall {
  return {
    tool: REGISTRY_EVOLUTION.name,
    what: REGISTRY_EVOLUTION.what,
    instruction: REGISTRY_EVOLUTION.ownInstruction,
    output: `${FAKE_MARK}. Смыслы сообщения «${request}» приняты в накопитель. Настоящий инструмент выделил бы из него облако смыслов, увеличил счётчик каждому и при достижении порога предложил бы новый элемент реестра признаков с правилами и атрибутами.`,
    // 🔒 «Автономное выполнение» — слово владельца: строка НЕ порождает следующую.
    next: "Автономное выполнение",
    status: 200,
  }
}

/** Превратить вызов заглушки в строку таблицы разбора. */
export function fakeRow(call: FakeCall, id: number): TaskRow {
  return {
    id,
    kind: "evolve",
    phrase: call.output,
    source: "http",
    tool: call.tool,
    toolWhat: call.what,
    instruction: call.instruction,
    next: call.next,
    // 🔒 ИМЯ ИНСТРУМЕНТА ЕДЕТ НАЧИНКОЙ, А НЕ ПРЯЧЕТСЯ В ТЕКСТЕ: по нему строку
    // найдут, когда заглушку заменят настоящим исполнителем.
    payload: { tool: call.tool, status: call.status, fake: true },
    at: nowMs(),
  }
}
