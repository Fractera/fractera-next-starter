import { nowMs, writeTask } from "./store"
import { REQUEST_CHANNELS } from "./types"
import type { RequestChannel, TaskObject } from "./types"

// ПЕРВАЯ СТРОКА РАЗБОРА — СЫРЬЁ, КАКИМ ОНО ПРИШЛО (91-3).
//
// 🔒 ОНА НЕСТРУКТУРИРОВАННАЯ, И В ЭТОМ ЕЁ СМЫСЛ. Прямые слова владельца:
// «создаст первую строку неструктурированные указав время поступления запрос от
// пользователя и канал». Она фиксирует то, что пришло, и НЕ ПЫТАЕТСЯ ПОНЯТЬ.
// Причина механическая: всё остальное в таблице — интерпретация, и без
// неинтерпретированного оригинала рядом её нечем проверить.
//
// 🔒 КЛАДЁТСЯ В САМОМ НАЧАЛЕ РАЗБОРА, ДО ВСЯКОЙ МОДЕЛИ. Строка обязана появиться
// раньше, чем что-либо может не получиться: иначе сообщение, на котором разбор
// упал, не оставит на экране никакого следа — а это ровно тот случай, ради
// которого экран и заведён.

/** Канал из свободной строки. Неизвестный — не канал, и это не молчаливая замена. */
function asChannel(raw: string | undefined): RequestChannel | null {
  return (REQUEST_CHANNELS as readonly string[]).includes(raw ?? "")
    ? (raw as RequestChannel)
    : null
}

/**
 * Открыть разбор: положить объект с одной строкой сырья.
 *
 * 🔒 ПРЕЖНИЙ ОБЪЕКТ ЗАМЕНЯЕТСЯ, И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА, А НЕ УПРОЩЕНИЕ. «Здесь
 * будет всего одна запись всегда»: стол один, и новый запрос кладут на него же.
 *
 * 🛑 ОТКАЗ ЗАПИСИ НЕ РОНЯЕТ РАЗБОР. Слой данных может не ответить (ноутбук без
 * ключа), и сообщение всё равно обязано быть принято и обработано: экран —
 * наблюдатель, а не участник. Возвращаем исход, а не бросаем исключение.
 */
export async function openTask(input: {
  text: string
  channel: string
  /** Кто прислал: имя в канале. Инструмент первой строки — `Telegram: @имя`. */
  who?: string
  messageId?: number
  hasAttachment?: boolean
}): Promise<{ ok: boolean; error?: string; at?: string }> {
  const channel = asChannel(input.channel)
  if (!channel) return { ok: false, error: "bad-channel" }

  const task: TaskObject = {
    intake: {
      // 🔒 ВРЕМЯ СТАВИТ КОД. Умолчание базы печатает СЕКУНДЫ, и прямое требование
      // владельца о миллисекундах через него неисполнимо — измерено в 91-2.
      at: nowMs(),
      channel,
      who: input.who,
      text: input.text,
      messageId: input.messageId,
      hasAttachment: Boolean(input.hasAttachment),
    },
    rows: [],
    decisions: [],
    done: false,
  }

  // 🔒 ВРЕМЯ ВОЗВРАЩАЕТСЯ НАРУЖУ, И ЭТО НЕ УДОБСТВО, А ЗАМОК (91-4). Пока идёт
  // разбор, на стол может лечь СЛЕДУЮЩИЙ запрос; строки, дописанные вслепую,
  // смешали бы два разбора в один. `at` — то, чем дописывающий узнаёт свой стол.
  const written = await writeTask(task)
  return { ...written, at: task.intake.at }
}
