import { slotsOf, type Slot, type TaskValue } from "./tools"
import type { Fact } from "@/lib/facts/types"

// ЧЕЛОВЕЧЕСКАЯ ФРАЗА СТРОКИ РАЗБОРА (91-5).
//
// 🔒 ФРАЗА ПОРОЖДАЕТСЯ ИЗ НАЧИНКИ, А НЕ ЛЕЖИТ РЯДОМ С НЕЙ. Разреши мы модели
// вернуть фразу отдельным полем — она разошлась бы с данными на первом же
// несовпадении, и человек поверил бы фразе, а в таблицу уехало бы другое. Тот же
// закон, что «порождать, а не перечислять», оплаченный числом инструментов
// четырежды за четыре дня.
//
// 🔒 РАСХОЖДЕНИЕ ЗАКРЫТО УСТРОЙСТВОМ, А НЕ ДИСЦИПЛИНОЙ: поля `phrase` нет в
// схеме инструмента, схема строгая, и лишнее поле отвергает вызов целиком.
// Второго источника у фразы физически не существует.

/** Дата хранится меткой времени; человеку она показывается днём, а не числом секунд. */
function human(s: Slot, v: TaskValue): string {
  if (s.valueType === "date" && typeof v === "number") {
    const iso = new Date(v * 1000).toISOString()
    // Полночь по UTC означает «день без часа»: час в такой записи выдуман, и
    // показывать его значило бы обещать точность, которой в словах не было.
    return iso.endsWith("T00:00:00.000Z") ? iso.slice(0, 10) : iso.slice(0, 16).replace("T", " ")
  }
  if (typeof v === "boolean") return v ? "да" : "нет"
  if (Array.isArray(v)) return v.join(", ")
  if (typeof v === "object") return `${v.lat}, ${v.lon}`
  return String(v)
}

/**
 * Фраза строки: значения признака человеческими словами.
 *
 * 🔒 ИМЯ СЛОТА ПОКАЗЫВАЕТСЯ ТОЛЬКО ТАМ, ГДЕ СЛОТОВ НЕСКОЛЬКО. У признака с одним
 * значением подпись «значение: 75» ничего не добавляет к «75 ₽», а место занимает.
 *
 * 🔒 ЕДИНИЦА ИДЁТ ЗА ЧИСЛОМ, И ЭТО НЕ УКРАШЕНИЕ: «40» и «40 ₽» — разные
 * утверждения, и первое читается как количество.
 */
export function phraseOf(fact: Fact | undefined, values: Record<string, TaskValue>): string {
  if (!fact) {
    // Признак, которого нет в реестре: показываем начинку как есть, а не молчим.
    return Object.entries(values)
      .map(([k, v]) => `${k}: ${String(v)}`)
      .join("; ")
  }

  const slots = slotsOf(fact)
  const many = slots.length > 1
  const parts: string[] = []

  for (const s of slots) {
    const v = values[s.name]
    if (v === undefined) continue
    const text = human(s, v) + (s.unit ? ` ${s.unit}` : "")
    parts.push(many ? `${s.title}: ${text}` : text)
  }

  // 🔒 ПУСТАЯ ФРАЗА НЕВОЗМОЖНА ПО УСТРОЙСТВУ — находка без значений не
  // создаётся вовсе, — но если она случится, честнее назвать признак, чем
  // отдать виду пустую ячейку: пустое место читается как поломка.
  return parts.length ? parts.join("; ") : fact.title
}
