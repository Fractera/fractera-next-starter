// ОБЪЕКТ РАЗБОРА ЗАПРОСА — сырьё одного диалога (91-2).
//
// 🔒 ЗАПИСЬ ВСЕГДА РОВНО ОДНА, И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-09-01, ДОСЛОВНО:
// «в отличие от того подхода который мы использовали раньше и предполагали либо
// бесконечное количество записей либо 500 здесь будет всего одна запись всегда и
// мы будем использовать этот объект Джейсон как сырые данные одного единственного
// объекта запроса и я уже говорил в будущем этот запрос будет перемещён в
// несколько таблиц и освобождён для следующего диалога с пользователем».
//
// Отсюда всё устройство: это НЕ история и не журнал, а рабочий стол, на котором
// лежит текущий запрос, пока его разбирают. Следующий запрос его заменяет.

/**
 * Род строки. Пять, и порядок здесь — порядок ИСПОЛНЕНИЯ, а не показа.
 *
 * 🔒 «РАЗРЕШЕНИЕ» СТОИТ ПЕРЕД «ПЛАНОМ», ХОТЯ ВЛАДЕЛЕЦ НАЗВАЛ ЕГО «РАСКРЫТИЕМ».
 * Его же слова о втором сценарии: «возникает ПРЕДВАРИТЕЛЬНОЕ УСЛОВИЕ для поиска
 * информации». Пока неизвестно, о каком кафе речь, план строить не из чего. Имя
 * и позиция разошлись, и это записано намеренно: иначе следующий агент положит
 * строку в конец, и разбор сломается тихо — «план» будет строиться по ссылке,
 * которую ещё никто не разрешил.
 */
//   intake  — запрос как пришёл: время с мс, канал, текст. До всякой модели.
//   extract — что вынуто из вложения: чек прочитан, из него адрес, товар, цена.
//   resolve — на что ссылается сообщение: из скольких выбрано и почему это.
//   plan    — какие признаки реестра в этом запросе есть.
//   reveal  — по строке на признак: значения и куда они лягут.
export const TASK_ROW_KINDS = ["intake", "extract", "resolve", "plan", "reveal"] as const
export type TaskRowKind = (typeof TASK_ROW_KINDS)[number]

/**
 * Канал, которым пришёл запрос.
 *
 * 🔒 СПИСОК ИЗ ОДНОГО ЗНАЧЕНИЯ ОБЪЯВЛЕН СПИСКОМ ИМЕННО ПОЭТОМУ. Слова владельца:
 * «в данный момент только Telegram теоретически это может быть WhatsApp». Строка
 * `"telegram"`, зашитая по коду, потребовала бы искать все места; список правится
 * одной правкой ВМЕСТЕ с перечислением.
 */
export const REQUEST_CHANNELS = ["telegram"] as const
export type RequestChannel = (typeof REQUEST_CHANNELS)[number]

/** Чем строка добыта. Отвечает на вопрос владельца «какие применены навыки, скрипты, функции». */
export const TASK_SOURCES = ["none", "model", "http", "rag", "table", "vector", "map"] as const
export type TaskSource = (typeof TASK_SOURCES)[number]

/**
 * Одно решение, принятое по дороге.
 *
 * 🔒 ЭТО ПЕРЕВОД `steps` АГЕНТА, А НЕ СОБСТВЕННЫЙ СБОР (91-7). `ToolLoopAgent`
 * отдаёт все вызовы и результаты сам; собирать их руками значило бы завести
 * второй источник, который разойдётся с первым.
 *
 * 🛑 КЛЮЧЕЙ И ПОЛНЫХ ПРОМПТОВ ЗДЕСЬ НЕ БЫВАЕТ. Объект читается дверью слоя и
 * однажды уедет в таблицы; ключ, попавший туда, оттуда уже не вынуть. Пишем,
 * О ЧЁМ спросили, а не чем.
 */
export type TaskDecision = {
  /** Время с миллисекундами. Ставит код, не база: умолчание базы печатает секунды. */
  at: string
  step: number
  /** Какой инструмент звали: имя признака или имя источника. */
  tool: string
  model?: string
  /** О чём спросили — коротко, без промпта целиком. */
  about: string
  ok: boolean
  /** Почему не вышло. Отказ — законный исход, и он объясняет, почему строк меньше. */
  reason?: string
}

/** Одна строка таблицы разбора. */
export type TaskRow = {
  id: number
  kind: TaskRowKind
  /**
   * Ключ признака реестра — у строк `reveal` и части `resolve`. Пусто у `intake`.
   * Пустой у `reveal` означает `no-fact`: признака под это в реестре НЕТ, и это
   * законный исход, а не потеря (закон владельца, сформулированный отрицанием).
   */
  fact?: string
  /**
   * Типизированная начинка — то, ради чего строка существует.
   *
   * 🔒 ПРОЗА НЕ ГОДИТСЯ ДЛЯ ЗАПИСИ, И В ЭТОМ БЫЛА ГЛАВНАЯ ДЫРА ПЕРВОГО ПЛАНА.
   * «Расход 40 рублей, четыре пирожка по 10» — предложение; в `value_num` его не
   * записать, и следующему шагу писать будет нечего. Начинка первична, фраза
   * СОБИРАЕТСЯ из неё (91-5).
   */
  payload?: Record<string, unknown>
  /** Человеческая фраза, порождённая из начинки. Не приходит от модели отдельно. */
  phrase: string
  source: TaskSource
  /**
   * Что будет сделано ДАЛЬШЕ по итогам этой строки.
   *
   * 🔒 ЭТО СЦЕПКА ТАБЛИЦЫ, А НЕ ПОДПИСЬ. Строка называет своё следующее
   * действие — и оно становится следующей строкой. Так таблица читается как ход
   * разбора, а не как список несвязанных находок (правка владельца 2026-09-02).
   *
   * 🔒 ОДНО ДЕЙСТВИЕ ЕСТЬ ВСЕГДА, КАКИМ БЫ НИ БЫЛ РАЗБОР: проверить, нет ли в
   * тексте прямого или косвенного указания на связь с другим сообщением.
   * Остальные зависят от того, что нашлось в реестре.
   */
  next?: string
  /** Чем спросили — инструкция инструменту. Пусто — инструмента не звали. */
  instruction?: string
  /** Насколько уверены. Осмысленно у `resolve`: там выбирают из нескольких. */
  confidence?: number
  /** Что отвергнуто и почему — у `resolve`. Догадка без альтернатив читается как вывод. */
  rejected?: { what: string; why: string }[]
  at: string
}

/** Сырьё: запрос, каким он пришёл. */
export type TaskIntake = {
  /** ISO с миллисекундами: `2026-09-02T21:14:07.482Z`. Требование владельца прямое. */
  at: string
  channel: RequestChannel
  /**
   * Кто прислал — имя в канале.
   *
   * 🔒 ИНСТРУМЕНТ ПЕРВОЙ СТРОКИ ЧИТАЕТСЯ КАК `Telegram: @roma_armstrong`, а не
   * просто «Telegram» (правка владельца): канал без человека не отвечает на
   * вопрос «от кого это пришло», а таблица разбора отвечает именно на него.
   */
  who?: string
  /** Текст дословно, без интерпретации. */
  text: string
  /** Идентификатор сообщения в канале — по нему разбор связывается с исходником. */
  messageId?: number
  /** Было ли вложение: от этого зависит, появится ли строка `extract`. */
  hasAttachment: boolean
}

/** Весь объект: одна запись, и другой не бывает. */
export type TaskObject = {
  intake: TaskIntake
  rows: TaskRow[]
  decisions: TaskDecision[]
  /** Разбор идёт или кончился. Строки появляются по мере готовности. */
  done: boolean
}
