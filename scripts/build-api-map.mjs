#!/usr/bin/env node
// build:api-map — реестр маршрутов одним файлом, чтобы искать чтением, а не обходом.
//
// 🔒 СОБИРАЕМЫЙ ДОКУМЕНТ, ПРАВКА РУКАМИ ЗАПРЕЩЕНА — как `PLATFORM-TOOLS.md`.
// Написанное здесь руками исчезнет при следующей сборке, и человек узнает об
// этом, заметив пропажу. Имена берутся из самих маршрутов (`// @api …`), потому
// что рядом с кодом они не расходятся с ним.
//
// Зачем вообще: обход `app/api/**` стоит агенту двадцати чтений и всё равно не
// отвечает «какой из них пишет нажатия» — имя видно только внутри файла. Один
// файл отвечает на это одним чтением.

import { writeFile, mkdir } from "node:fs/promises"
import { join, dirname } from "node:path"
import { collectRoutes } from "./check-api.mjs"

const OUT = join(process.cwd(), "development-docs", "API-MAP.md")

/**
 * Продукт, которому принадлежит маршрут, выводится из адреса: `/api/p1/...`
 * (правило четырёх корней продукта). Общий маршрут остаётся общим — навязывать
 * ему продукт значило бы соврать в поле, которое читают как правду.
 */
function productOf(url) {
  const m = /^\/api\/(p\d+)\//.exec(url)
  return m ? m[1] : "—"
}

const rows = await collectRoutes()
rows.sort((a, b) => a.url.localeCompare(b.url))

const body = `# API map

> **Собирается командой \`npm run build:api-map\` — не правьте руками.** Имена живут в самих маршрутах
> первой строкой (\`// @api …\`), потому что рядом с кодом они не расходятся с ним. Написанное здесь
> вручную исчезнет при следующей сборке.

Имя маршрута — то, чем его находят: 6–12 слов, глагол первым. Правило проверяется \`npm run check:api\`,
который стоит в \`prebuild\` — маршрут без имени роняет сборку.

Всего маршрутов: **${rows.length}**

| Адрес | Методы | Что делает | Продукт |
|---|---|---|---|
${rows.map((r) => `| \`${r.url}\` | ${r.methods.join(", ") || "—"} | ${r.name} | ${productOf(r.url)} |`).join("\n")}

## Как этим пользоваться

- **Ищете, куда писать данные?** Читайте столбец «что делает», а не имена папок: адрес говорит, где
  маршрут лежит, имя — что он делает, и это разные вопросы.
- **Заводите свой маршрут?** Первой строкой файла — \`// @api <6–12 слов>\`, затем \`npm run build:api-map\`.
- **Адрес не переименовывают ради красоты.** URL — публичный контракт: он в браузере, в журналах и в
  чужих интеграциях. Меняется имя в заголовке, оно ничего не ломает.
`

await mkdir(dirname(OUT), { recursive: true })
await writeFile(OUT, body, "utf-8")
console.log(`===API_MAP_BUILT=== ${rows.length} маршрутов → development-docs/API-MAP.md`)
