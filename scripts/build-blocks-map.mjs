// КОД БЛОКА — ЯЗЫК МЕЖДУ ВЛАДЕЛЬЦЕМ И АГЕНТОМ (шаг 50, 2026-08-30).
//
// 🔒 ЗАЧЕМ ОН ПОРОЖДАЕТСЯ ЗДЕСЬ. Владелец видит на витрине `quote01` и называет
// этот код в задаче: «собери секцию из этого и этого». Пока код существовал
// только на экране, агент шёл по навыку в эту сводку — и не находил его. Дефект
// худшего рода: путь построен, дисциплина есть, а на конце пути пусто.
// Разбор — `development-docs/reports/errors-block-identifiers-live-only-on-screen-and-reach-no-skill.md`.
//
// 🔒 КОД УКАЗЫВАЕТ НА ОБРАЗЕЦ, А НЕ НА ВИД, И РАЗНИЦА СУЩЕСТВЕННА. У вида
// `workspace` два образца — без верхнего ряда разделов и с ним, — и это ОДИН вид
// в двух настройках. Значит `workspace02` несёт больше, чем имя вида: он несёт
// ещё и вариант. Отсюда форма кода: имя вида плюс двузначный номер образца
// ЭТОГО вида.
//
// 🔒 СЧИТАЕТСЯ, А НЕ ПРОСТАВЛЯЕТСЯ РУКАМИ. «Абсолютно оригинальный» — свойство,
// которое либо держится устройством, либо не держится вовсе: проставленный номер
// повторится в день, когда у вида появится третий образец, и никто не вспомнит
// про второй.
//
// 🔒 ЧИСЛОВОЙ `id` ОСТАЁТСЯ — РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-08-30 (вариант B). `id`
// (`0015`) внутренний ключ панели; `code` (`quote01`) — язык общения с агентом.
// Два идентификатора у одной вещи допустимы ровно потому, что у них разные
// читатели и разные обязанности; сводить их в один владелец отказался осознанно.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Коды образцов по видам: `{ quote: ['quote01'], workspace: ['workspace01', 'workspace02'] }`.
 *
 * 🔒 ОБРАЗЦЫ ЧИТАЮТСЯ РЕГУЛЯРНЫМ ВЫРАЖЕНИЕМ ПО СТРОГОМУ ОТСТУПУ, и это не
 * небрежность. Импортировать `specimen.ts` генератор не может — это TypeScript с
 * импортами React-типов, а он обычный узловой скрипт. Отступ в четыре пробела
 * плюс конец строки отделяет запись ОБРАЗЦА от `kind` внутри его блоков: тех в
 * файле втрое больше, и без якоря счёт кодов был бы втрое больше правды.
 */
function specimenCodes() {
  const out = {}
  if (!existsSync(SPECIMEN_FILE)) return out
  const src = readFileSync(SPECIMEN_FILE, "utf8").replace(/\r\n/g, "\n")
  for (const m of src.matchAll(/^ {4}kind: '([a-zA-Z0-9]+)',$/gm)) {
    const kind = m[1]
    const list = (out[kind] ??= [])
    list.push(`${kind}${String(list.length + 1).padStart(2, "0")}`)
  }
  return out
}

// 🔒 ИСТОЧНИК ВИДОВ — РЕЕСТР `SECTIONS`, А НЕ РАЗБОР ТИПОВ. Первая редакция читала
// объединение `Block` регулярным выражением и нашла 24 вида из 29: определения с
// вложенными фигурными скобками (`metrics`, `flow`, `hero`, …) обрывались на первой
// закрывающей. Неполная сводка ХУЖЕ отсутствующей — по ней агент честно не возьмёт
// вид, которого «нет». Реестр же и есть закон: рендерер, не названный в нём, не
// существует для приложения.
function readKinds() {
  const src = readFileSync(INDEX, "utf8")
  const body = src.slice(src.indexOf("export const SECTIONS"))
  const inner = body.slice(body.indexOf("{") + 1, body.indexOf("}"))
  const kinds = inner.split(",").map(x => x.trim()).filter(Boolean)

  // Поля — по возможности из типов; не разобрались — честный прочерк, а не догадка.
  const typeLines = readFileSync(TYPES, "utf8").split("\n")
  return kinds.map(kind => {
    // Берём СТРОКУ ОБЪЯВЛЕНИЯ, а не первое вхождение имени: имя вида встречается и
    // в комментариях выше, и тогда в колонку полей уезжал сам ключ.
    const line = typeLines.find(l => l.trimStart().startsWith("|") && l.includes(`kind: '${kind}'`))
    let fields = ""
    // 🔒 ОДНОСТРОЧНОЕ ОБЪЯВЛЕНИЕ УЗНАЁТСЯ ПО ЗАКРЫВАЮЩЕЙ СКОБКЕ, А НЕ ПО ТОМУ,
    // ЧТО СТРОКА НАШЛАСЬ. Форм объявления три: всё в одну строку · `| {` отдельной
    // строкой · `| { kind: '…'` вместе, а поля столбиком ниже. Третья форма
    // находится строчным поиском и при этом многострочна — обрезанная по
    // несуществующей `}`, она давала почти пустое поле.
    if (line && line.includes("}")) {
      fields = line
        .replace(/^\s*\|\s*\{/, "")
        // 🔒 ЦИФРА В ИМЕНИ ВИДА — ЗАКОННА (`h2`, `h3`). Здесь стояло `[a-zA-Z]+`, и
        // у этих двух ключ не вычищался, уезжая в колонку полей.
        .replace(/kind:\s*'[a-zA-Z0-9]+';?/, "")
        .replace(/\}\s*$/, "")
        .trim()
    } else {
      // 🔒 МНОГОСТРОЧНОЕ ОБЪЯВЛЕНИЕ — ТОЖЕ ОБЪЯВЛЕНИЕ (шаг 50, найдено прогоном
      // холодного агента 2026-08-30).
      //
      // Виды, у которых полей больше двух-трёх, объявлены столбиком:
      //
      //     | {
      //         kind: 'workspace'
      //         menu: WorkspaceItem[]
      //         …
      //       }
      //
      // Строчный поиск такого объявления не находит вовсе, и в колонку полей
      // уезжал прочерк. Так молчали ЧЕТЫРЕ вида — `heroSplit`, `problemSolution`,
      // `noBill` и `workspace`.
      //
      // ✗ ЧЕМ ЭТО ОПЛАЧЕНО. Сводка обещает словами: «возьми поля образца из
      // строки — этого хватает, чтобы собрать секцию, не открывая ни одного
      // рендерера». Для этих четырёх обещание было ложью, и увидеть это стало
      // возможно только когда обещание прозвучало явно: холодный агент честно
      // пришёл сюда по закону из инструкции и вынужден был открыть ещё ТРИ файла
      // ровно там, где корпус обещал ноль.
      const start = typeLines.findIndex(
        (l, i) =>
          // Либо ключ на той же строке, что открывающая скобка, либо на одной из
          // ближайших трёх ниже — между ними может стоять комментарий поля.
          (l.trimStart().startsWith("| {") && l.includes(`kind: '${kind}'`)) ||
          (l.trim() === "| {" && typeLines.slice(i + 1, i + 4).some(x => x.includes(`kind: '${kind}'`))),
      )
      if (start >= 0) {
        const indent = typeLines[start].length - typeLines[start].trimStart().length
        const parts = []
        for (let i = start + 1; i < typeLines.length; i += 1) {
          const raw = typeLines[i]
          // Закрывающая скобка ОБЪЯВЛЕНИЯ — та, что не глубже открывающей плюс
          // два пробела: глубже лежат вложенные объекты самих полей.
          if (/^\s*\}/.test(raw) && raw.length - raw.trimStart().length <= indent + 2) break
          const t = raw.trim()
          // Комментарии — не поля, а их в таких объявлениях больше, чем полей.
          if (!t || t.startsWith("//") || t.startsWith("/*") || t.startsWith("*")) continue
          if (t.startsWith("kind:")) continue
          parts.push(t.replace(/[;,]$/, ""))
        }
        fields = parts.join("; ")
      }
    }
    // Труба ломает разметку таблицы — экранируем.
    return { kind, fields: fields.replace(/\|/g, "\\|") }
  })
}

/** Первая содержательная строка карточки — её и показываем как «что это». */
function cardSummary(kind) {
  const file = join(BLOCKS, `${kind}.md`)
  if (!existsSync(file)) return null
  const lines = readFileSync(file, "utf8").split("\n")
  const head = lines.find(l => l.startsWith("# "))
  return {
    title: head ? head.replace(/^#\s*/, "").trim() : kind,
  }
}

/** Таксономия читается один раз: её спрашивают и сводка, и каталог. */
const TAXONOMY_DATA = JSON.parse(readFileSync(TAXONOMY, "utf8"))

/**
 * Тип вида — из таксономии, а не из прозы карточки.
 *
 * 🔒 ЗДЕСЬ СТОЯЛ РАЗБОР СТРОКИ «**Семейство:**», И КОЛОНКА БЫЛА ПУСТА ЦЕЛИКОМ
 * (найдено 2026-08-22). Карточки давно пишутся по-английски и говорят
 * «**Type:**» — совпадений не находилось ни разу, и в порождённой сводке во всех
 * двадцати девяти строках стоял прочерк. Дефект ровно того сорта, что этот файл
 * заводился ловить: сводка выглядит целой, а одна её колонка не значит ничего.
 *
 * Источник теперь тот же, что у панели, — `taxonomy.json`. Он знает тип КАЖДОГО
 * вида, а не только тех одиннадцати, у которых есть карточка, и не зависит от
 * языка, на котором карточка написана.
 */
function familyOf(kind) {
  const t = TAXONOMY_DATA.kinds[kind]
  const type = TAXONOMY_DATA.types.find(x => x.id === (t?.type ?? "page-material"))
  return type?.title?.en ?? null
}

