// Превью статических изображений (шаг 506.2, заказ владельца 2026-08-13).
// Запуск: автоматически в `prebuild`/`predev`, вручную — `npm run images:previews`.
//
// ЗАЧЕМ. Картинка в вебе появляется рывком: сначала пустое место, потом сразу
// изображение. Пустое место двигает текст под собой, а рывок читается как
// «сайт тормозит», даже когда файл лёгкий. Лечение стандартное и старое:
// показать вместо пустоты крошечную размытую версию той же картинки — она
// весит сотни байт, приходит вместе с HTML и не требует ни одного запроса.
//
// 🔒 ПОЧЕМУ ЭТО СЧИТАЕТСЯ ЗДЕСЬ, А НЕ В БРАУЗЕРЕ И НЕ В РАНТАЙМЕ.
// Первоисточник (документация Next 16.3, `next/image`): `blurDataURL`
// добавляется автоматически ТОЛЬКО при статическом импорте `jpg/png/webp/avif`;
// дословно — «If the image is dynamic or remote, you must provide `blurDataURL`
// yourself». Наши посты хранят путь СТРОКОЙ (`heroPoster: '/blog-media/…'`),
// потому что данные поста обязаны оставаться данными, а не импортами кода.
// Строка для Next — динамический источник, и превью для неё обязаны дать мы.
//
// Считать на каждый запрос нельзя: декодирование изображения стоит десятки
// миллисекунд процессора, а страница обязана оставаться статикой. Поэтому —
// один раз на сборке, результат в сгенерированный модуль.
//
// РАЗМЕР ПРЕВЬЮ. Та же документация: «The image is automatically enlarged and
// blurred, so a very small image (10px or less) is recommended» и «A large
// blurDataURL may hurt performance». Поэтому 12 пикселей по ширине и webp —
// сотни байт, а не килобайты: строка едет в HTML КАЖДОЙ страницы, где стоит
// картинка, и её вес платится при каждой загрузке.
//
// SVG СЮДА НЕ ПОПАДАЕТ НАМЕРЕННО. Вектор масштабируется без потерь, Next его не
// оптимизирует по построению (`unoptimized` включается сам для `.svg`), и
// размытая копия весила бы больше оригинала: вектор обычно меньше килобайта.
// Анимированные тоже исключены — у них blur не имеет смысла.

import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const PUBLIC = path.join(ROOT, "public");
const OUT = path.join(ROOT, "lib", "images", "previews.generated.ts");

const RASTER = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

function walk(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (RASTER.has(path.extname(entry.name).toLowerCase())) out.push(full);
  }
  return out;
}

const files = walk(PUBLIC);
const entries = [];
let skippedAnimated = 0;

for (const file of files) {
  // Адрес, каким его пишет автор поста: от корня `public/`, со слэшами вперёд.
  const url = "/" + path.relative(PUBLIC, file).split(path.sep).join("/");
  try {
    const image = sharp(file);
    const meta = await image.metadata();

    if ((meta.pages ?? 1) > 1) { skippedAnimated++; continue; }
    if (!meta.width || !meta.height) continue;

    const tiny = await sharp(file)
      .resize({ width: 12, withoutEnlargement: true })
      .webp({ quality: 40 })
      .toBuffer();

    entries.push({
      url,
      width: meta.width,
      height: meta.height,
      blurDataURL: `data:image/webp;base64,${tiny.toString("base64")}`,
    });
  } catch (e) {
    // Битый файл не имеет права валить сборку: страница без превью работает,
    // сборка, упавшая на одной картинке, — нет.
    console.warn(`  превью пропущено: ${url} (${e.message})`);
  }
}

entries.sort((a, b) => (a.url < b.url ? -1 : 1));

const body = entries
  .map(e => `  ${JSON.stringify(e.url)}: { width: ${e.width}, height: ${e.height}, blurDataURL: ${JSON.stringify(e.blurDataURL)} },`)
  .join("\n");

const file = `// AUTO-GENERATED by scripts/generate-image-previews.mjs — DO NOT EDIT.
// Regenerated on every build/dev (npm prebuild/predev). Gitignored.
// Size, and a tiny blurred copy, of every raster image in public/.

export type StaticImagePreview = { width: number; height: number; blurDataURL: string }

export const IMAGE_PREVIEWS: Record<string, StaticImagePreview> = {
${body}
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, file, "utf8");

const bytes = entries.reduce((sum, e) => sum + e.blurDataURL.length, 0);
const avg = entries.length ? Math.round(bytes / entries.length) : 0;
console.log(`превью: ${entries.length} изображений, средний вес строки ${avg} байт${skippedAnimated ? `, анимированных пропущено: ${skippedAnimated}` : ""}`);
