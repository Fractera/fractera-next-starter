// Картинки-заглушки для слотов `images.*` настроек приложения.
// Запуск: npm run images:placeholders
//
// ЗАЧЕМ. Слоты `notFound-*`, `error500-*`, `loading-*`, `homePage-*` панель
// предлагала заполнить с первого дня, но приложение их не читало, а дефолтом
// стоял `null` — то есть даже заполненный слот показывать было нечем и негде.
// Страница 404 при этом картинку имела: путь `/404-logo.png` был вписан прямо в
// компонент, мимо настроек. Один слот жил хардкодом, восемь не жили вообще.
//
// Здесь рождается ВТОРАЯ половина механизма — файлы, на которые указывают
// умолчания в `config/app-config.defaults.ts`. Свежий проект показывает знак
// Fractera на любой странице-заглушке; владелец загружает своё в панели, и его
// картинка перекрывает эту без пересборки.
//
// 🔒 ПОЧЕМУ ДВА ТОНА, А НЕ ОДИН ФАЙЛ. Знак нарисован белым по НЕПРОЗРАЧНОМУ
// чёрному полю. На тёмной странице он к месту, на светлой это чёрный квадрат
// посреди белого листа. Ровно для этого слоты и заведены парами `-dark`/`-light`:
// пара без разницы в тоне — пара впустую.
//
// 🔒 ТРИ ФАЙЛА НА ВОСЕМЬ СЛОТОВ. Шесть слотов ошибок делят два файла знака, оба
// слота главной — один скриншот. Восемь копий одного PNG были бы ровно тем
// мусором, ради вычистки которого эта работа и начата.

import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const ROOT = path.resolve(import.meta.dirname, '..')
const OUT = path.join(ROOT, 'public', 'placeholders')

// 🔒 ИСХОДНИК ЛЕЖИТ ВНЕ `public/`, И ЭТО НЕ ПРИДИРКА. Он раздавался браузеру как
// `/404-logo.png` — 86 КБ, доступные любому, при том что страница ссылалась на
// него лишь пока путь был вписан в компонент. Материал, из которого собирают
// файлы, и сами файлы — разные вещи: первый нужен сборке, второму место в
// раздаче. Смешение как раз и оставляет в `public/` картинки, которых никто не
// запрашивает, и никто уже не помнит, можно ли их удалить.
const SOURCE_LOGO = path.join(ROOT, 'assets', 'brand', 'fractera-mark.png')

fs.mkdirSync(OUT, { recursive: true })

if (!fs.existsSync(SOURCE_LOGO)) {
  console.error(`Нет исходного знака: ${SOURCE_LOGO}`)
  process.exit(1)
}

// Тёмный вариант — исходник как есть: белый знак на чёрном.
const dark = await sharp(SOURCE_LOGO).png().toBuffer()
fs.writeFileSync(path.join(OUT, 'logo-dark.png'), dark)

// Светлый вариант — инверсия: чёрный знак на белом.
//
// `negate` с `alpha: false` переворачивает только цветовые каналы; прозрачность
// (её здесь нет, но исходник могут заменить) остаётся нетронутой — иначе
// невидимый фон стал бы непрозрачным чёрным прямоугольником.
const light = await sharp(SOURCE_LOGO).negate({ alpha: false }).png().toBuffer()
fs.writeFileSync(path.join(OUT, 'logo-light.png'), light)

console.log('placeholders/logo-dark.png   — белый знак на чёрном (тёмная тема)')
console.log('placeholders/logo-light.png  — чёрный знак на белом (светлая тема)')

// Иллюстрация главной НЕ генерируется: это снимок экрана, а не производная от
// знака. Лежит в git рядом с остальными и проверяется здесь только на наличие —
// её пропажа обязана быть шумной, иначе главная тихо останется без правой колонки.
const home = path.join(OUT, 'home.jpg')
if (fs.existsSync(home)) {
  const meta = await sharp(home).metadata()
  console.log(`placeholders/home.jpg        — на месте, ${meta.width}x${meta.height}`)
} else {
  console.log('placeholders/home.jpg        — ОТСУТСТВУЕТ (иллюстрация главной, в git)')
  process.exitCode = 1
}
