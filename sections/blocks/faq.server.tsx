import type { SectionRenderer } from '@/sections/contract'
import { H2 } from '@/components/ui/typography'
import { getPageUi } from '@/lib/content/page-ui'

// ВОПРОСЫ И ОТВЕТЫ — последняя содержательная секция страницы.
//
// 🔒 РИСУНОК ПЕРЕНЕСЁН ИЗ ФАБРИКИ СТРАНИЦЫ БЕЗ ЕДИНОГО ИЗМЕНЕНИЯ (шаг 542), и
// это условие приёмки, а не осторожность. Задача шага — свести два источника
// разметки в один, а не перерисовать семь живых страниц заодно: смешай их, и
// после сборки уже не скажешь, что именно поехало — переезд или новый вид.
//
// 🔒 ЗАГОЛОВОК РАЗДЕЛА — СЛОВО МЕХАНИЗМА, А НЕ МАТЕРИАЛА. «Частые вопросы»
// пишет не автор страницы: это подпись самой конструкции, и она уже переведена
// на десять языков в `lib/content/page-ui.ts`. Вписать её в языковую ячейку
// каждой страницы значило бы завести десять копий одного слова, которые
// разойдутся на первой же правке.
//
// 🔒 ЯКОРЬ ПОСТОЯННЫЙ (`faq-heading`), И ИЗ ЭТОГО СЛЕДУЕТ ОДИН РАЗДЕЛ НА
// СТРАНИЦУ. Постоянный якорь — то, на что можно дать ссылку снаружи; ключ блока
// таким свойством не обладает. Второй такой раздел на той же странице сделал бы
// два одинаковых `id`, поэтому вид не повторяется — общее правило владельца для
// секций (2026-08-22), здесь оно ещё и техническое.
//
// 🔒 `<dl>` — РАЗМЕТКА ПО СУЩЕСТВУ, а не выбор оформления: вопрос и ответ это
// пара «термин — определение», и поисковик читает её как пару. Заменить на
// `<div>` с заголовками значит потерять связь между ними ровно там, где она
// единственное содержание раздела.
export const faq: SectionRenderer<'faq'> = (b, ctx) => {
  const heading = b.title ?? getPageUi(ctx.lang).faqHeading
  return (
    <section key={ctx.key} aria-labelledby="faq-heading" className="mt-12 border-t border-border pt-10">
      <H2 id="faq-heading">{heading}</H2>
      <dl className="mt-6 flex flex-col gap-4">
        {b.items.map((f, i) => (
          <div key={`${ctx.key}-${i}`} className="rounded-2xl border border-border bg-muted/40 p-5">
            <dt className="text-base font-semibold text-foreground">{f.q}</dt>
            <dd className="mt-2 text-[15px] leading-relaxed text-muted-foreground">{f.a}</dd>
          </div>
        ))}
      </dl>
    </section>
  )
}
