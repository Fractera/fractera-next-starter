import Link from 'next/link'
import { Plus } from 'lucide-react'
import type { SectionRenderer } from '@/sections/contract'
import { DASHED_CARD } from '@/lib/ui/dashed-card'

// ПРИГЛАШЕНИЕ В ПУНКТИРНОЙ РАМКЕ — место, где чего-то ещё нет.
//
// 🔒 ЭТО НЕ `cta`, И РАЗНИЦА ПО СУЩЕСТВУ, А НЕ ПО ОФОРМЛЕНИЮ. `cta` — сплошная
// кнопка: «сделайте следующий шаг», она про ГОТОВОЕ действие. Здесь пунктир, и
// он говорит человеку ровно одно: **здесь ПОКА ПУСТО, и это место можно
// занять**. Пунктирная рамка читается как незаполненная форма — этим приёмом
// живут все редакторы, и объяснять его не приходится.
//
// 🔒 ВЕСЬ БЛОК — ССЫЛКА, А НЕ ССЫЛКА ВНУТРИ БЛОКА. Попасть по такой карточке
// должно быть так же легко, как промахнуться мимо неё — трудно; то же правило,
// что у карточек карты пути.
//
// 🔒 РИСУНОК ОБЩИЙ С ОСТРОВКОМ ЗАЯВКИ (`lib/ui/dashed-card.ts`), и это главное
// решение вида. Такая же карточка стоит на страницах подвала, где она КНОПКА и
// открывает окно; здесь она ССЫЛКА и ведёт по адресу. Природа разная, вид один —
// значит класс живёт в одном месте, иначе две пунктирные карточки разойдутся на
// первой правке темы. ✗ оплачено шагом 70.
//
// 🔒 ПОДПИСЬ ОБЯЗАТЕЛЬНА, ПОЯСНЕНИЕ — НЕТ. Карточка без слов есть пустой
// прямоугольник: человек видит место, но не знает, что здесь появится.
export const invite: SectionRenderer<'invite'> = (b, { key: k }) => (
  <Link key={k} href={b.href} data-invite-card className={DASHED_CARD}>
    <Plus size={16} aria-hidden />
    <span>{b.label}</span>
  </Link>
)
