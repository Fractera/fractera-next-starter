import type { SectionRenderer } from '@/sections/contract'
import { inline } from '@/lib/content/blocks/inline'
import { PullQuote } from '@/sections/pull-quote.server'

// Крупное утверждение в разрядку — то, ради чего написан раздел.
//
// 🔒 ТОТ ЖЕ РИСУНОК, ЧТО У ЦИТАТЫ ВЛАДЕЛЬЦА, НО БЕЗ ПОДПИСИ, И ЭТО РАЗНИЦА ПО
// СУЩЕСТВУ, А НЕ ЭКОНОМИЯ РАЗМЕТКИ. `founder` подписан именем и фотографией из
// настроек: так помечают слова ЧЕЛОВЕКА. Правило продукта («пока хоть один
// кейс не подтверждён, агент отказывается строить») человек не произносил — его
// устанавливает продукт. Подпись под ним приписала бы владельцу фразу, которой
// он не говорил, причём выглядело бы это совершенно убедительно.
//
// Рисунок общий (`sections/pull-quote.server.tsx`) — значит два вида не
// разойдутся; различает их ровно наличие подписи.
export const statement: SectionRenderer<'statement'> = (b, { key: k }) => (
  <PullQuote key={k}>{inline(b.text, k)}</PullQuote>
)
