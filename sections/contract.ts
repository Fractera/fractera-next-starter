import type { ReactNode } from 'react'
import type { Block } from '@/lib/content/blocks/types'
import type { PostBodyUi } from '@/lib/content/post-body-ui'

// ДОГОВОР ДИЗАЙНА С ПЛАТФОРМОЙ (шаг 508). Единственный файл, который обязан
// прочитать тот, кто делает новый дизайн.
//
// 🔒 ЧТО ЗДЕСЬ ЕСТЬ, А ЧЕГО НЕТ. Здесь — форма рендерера и форма манифеста.
// Здесь НЕТ ни одного цвета, ни одного класса и ни одной строки текста: договор
// описывает, ЧТО дизайн обязан уметь, и молчит о том, КАК он это делает. Первая
// же деталь оформления, просочившаяся в договор, станет общей для всех дизайнов
// и обесценит слово «дизайн».
//
// 🔒 ФОРМА ДАННЫХ ДИЗАЙНУ НЕ ПРИНАДЛЕЖИТ. Виды секций и их поля объявлены в
// `lib/content/blocks/types.ts` — один каталог на все дизайны. Дизайн решает,
// как выглядит `quote`, и не решает, из чего `quote` состоит: иначе материал,
// написанный под одним дизайном, перестанет существовать под другим, а вместе с
// ним рассыплется обещание «ваш контент останется вашим при смене оформления».
// Нужна возможность, которой в каталоге нет, — вид добавляется в КАТАЛОГ, и
// тогда у каждого дизайна встаёт честный вопрос: рисую или объявляю непокрытым.

/** Всё, что рендерер получает сверх самого блока. */
export type SectionCtx = {
  lang: string
  /** Подписи, которые печатает сам механизм (кнопка `docref` и т. п.). */
  ui: PostBodyUi
  /** React-ключ этого блока; он же префикс ключей для его внутренностей. */
  key: string
  /** Нарисовать вложенные блоки — ими пользуются контейнеры. */
  renderBlocks: (blocks: Block[], lang: string, ui: PostBodyUi, keyPrefix?: string) => ReactNode[]
}

type BlockOf<K extends Block['kind']> = Extract<Block, { kind: K }>

/** Рендерер одного вида секции. */
export type SectionRenderer<K extends Block['kind']> = (block: BlockOf<K>, ctx: SectionCtx) => ReactNode

/**
 * Набор рендереров дизайна.
 *
 * 🔒 ЧАСТИЧНЫЙ НАМЕРЕННО. Дизайн не обязан покрывать все виды: у одного есть
 * карточка с картинкой, у другого нет, и это законное состояние, а не поломка.
 * Непокрытый вид не подставляется молча из дефолтного набора — что с ним делать,
 * решает манифест (`inherits`), а `npm run read:sections` печатает разницу как
 * задачу. Тихий фолбэк дал бы страницу в двух почерках и впечатление
 * законченного дизайна там, где половина не написана.
 */
export type SectionSet = {
  [K in Block['kind']]?: SectionRenderer<K>
}

/** Паспорт дизайна: чем он себя объявляет. */
export type DesignManifest = {
  /** Имя папки в `sections/` — оно же значение `design` в манифесте проекта. */
  design: string
  /** Виды, которые дизайн рисует сам. Считается из набора, а не пишется руками. */
  covers: Block['kind'][]
  /**
   * Брать ли недостающие виды у дизайна по умолчанию.
   *
   * `false` — честный отказ: непокрытый вид виден как непокрытый.
   * `true` — сознательная смесь почерков; витрина помечает унаследованное.
   */
  inherits: boolean
}

/** Собрать манифест из набора: список покрытого не расходится с кодом. */
export function manifestOf(design: string, set: SectionSet, inherits: boolean): DesignManifest {
  return {
    design,
    covers: Object.keys(set) as Block['kind'][],
    inherits,
  }
}
